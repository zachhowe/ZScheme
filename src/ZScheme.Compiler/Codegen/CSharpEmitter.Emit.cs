using System.Globalization;
using System.Text;
using ZScheme.Compiler.Ir;
using ZScheme.Compiler.Types;

namespace ZScheme.Compiler.Codegen;

public sealed partial class CSharpEmitter
{
    public string Emit(IrNode node)
    {
        Log.Debug(
            "CSharpEmitter: emitting class {ClassName} in namespace {Namespace}",
            className,
            ns
        );
        Log.Debug(
            "CSharpEmitter: funcMap={FuncMapCount} entries, typeMap={TypeMapCount} entries, importedModules={ImportedModuleCount}, precompiledMap={PrecompiledMapCount}",
            _funcToModuleClass.Count,
            _typeToModuleClass.Count,
            importedModules?.Count ?? 0,
            precompiledModuleMap?.Count ?? 0
        );
        _sb.Clear();
        // Lower tail self-calls to TcoJump back-edges (marking their functions IsTcoLoop) so
        // self-recursion emits as a `while(true)` loop. Async functions included: the loop
        // emitter handles `await`. Unlike the IL backend the C# emitter does not hoist, so this
        // simply runs first, before any walk of the tree — which also means an awaited tail
        // self-call arrives here un-A-normalized, the shape TailCallLowering's `let` peel exists
        // to keep matching across both backends.
        //
        // Inlined source modules are lowered alongside the main IR, not by the callers that
        // assemble them: a package library emits with an empty main IR and every function
        // arriving as an imported module, so lowering only `node` would leave the whole library
        // recursive. The construction-time maps built from `importedModules` key off names and
        // signatures, which this rewrite does not touch.
        var tco = new TailCallLowering();
        node = tco.Rewrite(node);
        importedModules = tco.RewriteModules(importedModules);
        // Register the current module's collision-renamed type names before any emission so
        // declarations and references (which may forward-reference a type) resolve alike.
        RegisterCurrentTypeEmitNames(node);
        var mainStatements = new List<IrNode>();

        if (!suppressVersionPreamble)
            EmitLine($"// <auto-generated by ZScheme compiler {CompilerInfo.VersionString}>");
        EmitLine("#nullable enable");
        EmitLine();
        if (clrUsings is { Count: > 0 })
        {
            foreach (var usingNs in clrUsings)
                EmitLine($"using {usingNs};");
            EmitLine();
        }

        EmitLine($"namespace {ns};");
        EmitLine();
        EmitTypeDeclarationsInline(node);
        EmitLine();

        if (HasProgramContent(node))
        {
            CollectModuleNames(node);

            EmitLine($"public static class {className}");
            EmitLine("{");
            _indent++;

            if (node is IrNode.Seq seq)
                foreach (var child in seq.Nodes)
                    EmitTopLevel(child, mainStatements);
            else
                EmitTopLevel(node, mainStatements);

            if (mainStatements.Count > 0)
            {
                EmitLine();
                EmitLine($"static {className}()");
                EmitLine("{");
                _indent++;
                // EmitUnitStatement, not a bare `{expr};`: the value is discarded here, and
                // a statement-form node (a top-level `use`) must emit its native C# form
                // rather than the immediately-invoked lambda EmitExpr would produce.
                foreach (var stmt in mainStatements)
                    EmitUnitStatement(stmt);
                _indent--;
                EmitLine("}");
            }

            // No entry-point wrapper: the user's `main` is emitted as a normal `public static`
            // method named `Main` (Int -> int, Unit -> void, async -> Task/Task<int>, param
            // -> string[]), which Roslyn discovers as the entry point directly. The signature is
            // guaranteed valid by EntryPointValidator. HasEntryPoint is set during EmitTopLevel.

            _indent--;
            EmitLine("}");
        }

        Log.Debug("CSharpEmitter: emit complete, {OutputLength} chars", _sb.Length);

        // Emit imported module classes (type declarations nested inside, plus functions/values)
        if (importedModules is { Count: > 0 })
            foreach (var (moduleClassName, defs) in importedModules)
            {
                Log.Debug(
                    "CSharpEmitter: processing imported module {ModuleClassName}, {DefCount} definitions",
                    moduleClassName,
                    defs.Count
                );
                var hasContent = defs.Any(d =>
                    d
                        is IrNode.FuncDef
                            or IrNode.Let
                            or IrNode.ClrCall
                            or IrNode.Call
                            or IrNode.Throw
                            or IrNode.Await
                            or IrNode.Use
                            or IrNode.WithHandlers
                            or IrNode.RecordDecl
                            or IrNode.UnionDecl
                            or IrNode.ClassDecl
                            or IrNode.InterfaceDecl
                );
                if (!hasContent)
                    continue;

                EmitLine();
                EmitLine($"public static class {moduleClassName}");
                EmitLine("{");
                _indent++;

                // Emit type declarations inside the module class
                foreach (var def in defs)
                    switch (def)
                    {
                        case IrNode.RecordDecl rec:
                            EmitLine(EmitRecordDecl(rec));
                            EmitLine();
                            break;
                        case IrNode.UnionDecl union:
                            EmitLine(EmitUnionDecl(union));
                            EmitLine();
                            break;
                        case IrNode.ClassDecl classDecl:
                            EmitClassDecl(classDecl);
                            EmitLine();
                            break;
                        case IrNode.InterfaceDecl ifaceDecl:
                            EmitInterfaceDecl(ifaceDecl);
                            EmitLine();
                            break;
                    }

                var moduleInitStatements = new List<IrNode>();
                foreach (var def in defs)
                    switch (def)
                    {
                        case IrNode.FuncDef func:
                            EmitFuncDef(func);
                            break;
                        case IrNode.Let let:
                            EmitLine(
                                $"public static {TypeToCs(LetVarType(let))} {SanitizeFunc(let.EmitName, let.VarName)} = {EmitExpr(let.Value)};"
                            );
                            if (let.Body is not IrNode.UnitConst)
                                moduleInitStatements.Add(let.Body);
                            break;
                        case IrNode.ClrCall:
                        case IrNode.Call:
                        case IrNode.Throw:
                        case IrNode.Await:
                        case IrNode.Use:
                        case IrNode.WithHandlers:
                            moduleInitStatements.Add(def);
                            break;
                    }

                if (moduleInitStatements.Count > 0)
                {
                    EmitLine();
                    EmitLine($"static {moduleClassName}()");
                    EmitLine("{");
                    _indent++;
                    // See the main module's static constructor above: EmitUnitStatement so a
                    // `use` emits a native `using` and a non-statement expression is discarded
                    // through `_ =` rather than emitted bare (CS0201).
                    foreach (var stmt in moduleInitStatements)
                        EmitUnitStatement(stmt);
                    _indent--;
                    EmitLine("}");
                }

                _indent--;
                EmitLine("}");
            }

        return _sb.ToString();
    }

    private void EmitTopLevel(IrNode node, List<IrNode> mainStatements)
    {
        switch (node)
        {
            case IrNode.FuncDef func:
                if (func.Name == "main")
                    HasEntryPoint = true;
                EmitFuncDef(func);
                break;
            case IrNode.RecordDecl rec:
                Log.Debug(
                    "CSharpEmitter: emitting record {RecordName} inside module class",
                    rec.Name
                );
                EmitLine(EmitRecordDecl(rec));
                EmitLine();
                break;
            case IrNode.UnionDecl union:
                Log.Debug(
                    "CSharpEmitter: emitting union {UnionName} inside module class",
                    union.Name
                );
                EmitLine(EmitUnionDecl(union));
                EmitLine();
                break;
            case IrNode.ClassDecl classDecl:
                EmitClassDecl(classDecl);
                EmitLine();
                break;
            case IrNode.InterfaceDecl ifaceDecl:
                EmitInterfaceDecl(ifaceDecl);
                EmitLine();
                break;
            case IrNode.Let let:
                EmitLine(
                    $"public static {TypeToCs(LetVarType(let))} {SanitizeFunc(let.EmitName, let.VarName)} = {EmitExpr(let.Value)};"
                );
                if (let.Body is not IrNode.UnitConst)
                    EmitTopLevel(let.Body, mainStatements);
                break;
            case IrNode.ClrCall:
            case IrNode.Call:
            case IrNode.Throw:
            case IrNode.Await:
            // A bare top-level `use` or `with-handlers` runs for effect in the static
            // constructor, like any other top-level statement. Without these cases it matches
            // nothing and the whole form — resource/body, or body and every handler alike —
            // is silently dropped from the output.
            case IrNode.Use:
            case IrNode.WithHandlers:
                mainStatements.Add(node);
                break;
        }
    }

    private void EmitFuncDef(IrNode.FuncDef func)
    {
        Log.Debug(
            "CSharpEmitter: emitting function {FuncName}, IsAsync={IsAsync}, TypeParams={TypeParamCount}",
            func.Name,
            func.IsAsync,
            func.TypeParams?.Count ?? 0
        );
        var bodyStrategy =
            func.IsTcoLoop ? "TCO"
            : func.IsAsync && ContainsAwait(func.Body) ? "async-statements"
            : WantsStatementForm(func.Body) ? "statements"
            : func.Body is IrNode.Throw ? "throw"
            : "expression";
        Log.Debug(
            "CSharpEmitter: function {FuncName} body strategy: {Strategy}",
            func.Name,
            bodyStrategy
        );
        var prevTypeParams = _currentTypeParams;
        var prevFuncTypeVarMap = _currentFuncTypeVarMap;

        if (func.TypeParams is { Count: > 0 })
        {
            _currentFuncTypeVarMap = BuildTypeVarMap(func);
            _currentTypeParams = new HashSet<string>(func.TypeParams);
        }

        EmitAttributes(func.Attributes);
        var asyncPrefix = func.IsAsync ? "async " : "";
        var retTypeStr = func.IsAsync
            ? func.ReturnType == ZType.Unit
                ? "System.Threading.Tasks.Task"
                : $"System.Threading.Tasks.Task<{TypeToCs(func.ReturnType)}>"
            : ReturnTypeToCs(func.ReturnType);
        var parms = string.Join(", ", func.Params.Select(FormatParam));
        var typeParamStr = func.TypeParams is { Count: > 0 }
            ? $"<{string.Join(", ", func.TypeParams)}>"
            : "";

        var whereClause = FormatWhereConstraints(func.TypeParamConstraints);
        EmitLine(
            $"public static {asyncPrefix}{retTypeStr} {SanitizeFunc(func.EmitName, func.Name)}{typeParamStr}({parms}){whereClause}"
        );
        EmitLine("{");
        _indent++;
        _localBindings.Clear();
        // Parameters are local bindings: they must shadow same-named imported
        // module functions during reference resolution (EmitVarRef), otherwise a
        // parameter like `length` would resolve to an unrelated module export
        // (e.g. concurrent/bag's `length`) that happens to be in scope.
        foreach (var p in func.Params)
            _localBindings.Add(p.Name);
        _localRenames.Clear();
        BeginDeclarationSpace(func.Params);

        if (func.IsTcoLoop)
            EmitTailRecursiveLoop(func.Body, func.ReturnType, func.IsAsync);
        else if (func.IsAsync && ContainsAwait(func.Body))
            EmitAsyncStatementsBody(func.Body, IsAsyncVoidReturn(func.ReturnType));
        else if (WantsStatementForm(func.Body))
            // Flatten let-spines and if-with-let-branch bodies into plain locals /
            // if-else blocks instead of emitting an immediately-invoked lambda. An async
            // function reaches this only when the branch above did not claim it, i.e. when
            // its body contains no `await` at all — so the sync walker used here can never
            // bury an `await` inside a non-async lambda (CS4034). EmitInstanceMethodBody
            // makes the same call for method bodies.
            EmitStatementsBody(func.Body, func.ReturnType, inLoop: false, isAsync: false);
        else if (
            func.Body is IrNode.Throw
            || (func.IsAsync && func.ReturnType == ZType.Unit)
            || func.ReturnType == ZType.Unit
        )
            EmitUnitStatement(func.Body);
        else
            EmitLine($"return {EmitExpr(func.Body)};");

        _indent--;
        EmitLine("}");
        EmitLine();

        _currentTypeParams = prevTypeParams;
        _currentFuncTypeVarMap = prevFuncTypeVarMap;
    }

    /// True when <paramref name="node"/> in C# statement position must be elided.
    /// The Unit literal `()` lowers to `default(System.ValueTuple)`, a
    /// value-producing expression that is not a legal C# statement (CS0201: "Only
    /// assignment, call, increment, decrement, await, and new object expressions
    /// can be used as a statement"). Evaluating the Unit literal has no side
    /// effects, so it is dropped. Other Unit-typed expressions (e.g. void CLR
    /// calls, `set!`) remain valid statements and are emitted unchanged.
    private static bool IsElidableUnitStatement(IrNode node) => node is IrNode.UnitConst;

    /// True when <paramref name="node"/> emits a C# expression that is itself a
    /// legal statement. CS0201 permits only assignment, call, increment,
    /// decrement, await, and new-object expressions as statements, so a node of
    /// one of these kinds can be emitted bare in statement position even when its
    /// value is discarded. Any other value-producing expression (a literal, var
    /// ref, operator, ternary (`if`), switch (`match`), etc.) must instead be
    /// discarded via `_ = expr;`.
    ///
    /// `Let`/`WithHandlers` lower to an immediately-invoked-lambda form
    /// (`((Func&lt;T&gt;)(…))()`, or `(await (…)())` for the async handler case) — an
    /// invocation/await, hence a legal statement. Conservative in the other
    /// direction: any node not listed falls to the always-valid `_ =` form, which
    /// is sound because every node that emits a genuinely *void*-typed C#
    /// expression (a void call/await/throw, where `_ = …` would itself be illegal)
    /// is listed here and so never reaches the `_ =` branch.
    private static bool IsValidStatementExpr(IrNode node) =>
        node switch
        {
            // A MethodCall is a legal bare statement only when it emits an
            // invocation or an assignment. The property/indexer *get* variants
            // (`IsProperty`/`IsIndexer` with no corresponding `…Set`) emit a bare
            // member- or element-access expression (`receiver.X`, `receiver[i]`),
            // which CS0201 forbids in statement position; those must fall through
            // to the always-legal `_ = …` form in DiscardStatement. The *set*
            // variants emit an assignment and stay valid.
            IrNode.MethodCall mc => !(mc.IsProperty || mc.IsIndexer)
                || mc.IsPropertySet
                || mc.IsIndexerSet,
            IrNode.Call
            or IrNode.ClrCall
            or IrNode.SuperMethodCall
            or IrNode.Await
            or IrNode.SetField
            or IrNode.Throw
            or IrNode.Let
            or IrNode.Use
            or IrNode.WithHandlers => true,
            _ => false,
        };

    private void EmitUnitStatement(IrNode body)
    {
        if (IsElidableUnitStatement(body))
            return;
        // A discarded Unit-typed `if` must be emitted as a statement-form
        // if/else, not the ternary `EmitExpr` produces: a taken branch may be a
        // genuinely void-typed C# expression (a void CLR call wrapped as Unit,
        // e.g. `vector-set!`), which is illegal as a ternary operand (CS0173) and
        // illegal to assign through `_ =` (CS0201). Recursing into
        // EmitUnitStatement discards each branch for effect, the same way the
        // other statement-context emitters (EmitStatementsBody,
        // EmitAsyncStatementsBody) already render `if`. This is the path taken by
        // the `when`/`unless` macros, which desugar to
        // `(if test (begin <side effects>) ())`.
        if (body is IrNode.If @if)
        {
            EmitLine($"if ({EmitExpr(@if.Condition)})");
            EmitLine("{");
            _indent++;
            EmitUnitStatement(@if.Then);
            _indent--;
            EmitLine("}");
            EmitLine("else");
            EmitLine("{");
            _indent++;
            EmitUnitStatement(@if.Else);
            _indent--;
            EmitLine("}");
            return;
        }
        // A discarded `use` is already in statement position, so emit the native C#
        // `using` statement rather than the immediately-invoked lambda EmitUseExpr
        // would wrap it in. Its body is discarded in turn.
        if (body is IrNode.Use use)
        {
            EmitUseStmt(use, EmitUnitStatement);
            return;
        }
        // Likewise a discarded `with-handlers`: it is already in statement position, so emit
        // the bare try/catch rather than the immediately-invoked lambda EmitWithHandlers
        // would wrap it in. Body and every handler are discarded in turn.
        if (body is IrNode.WithHandlers withHandlers)
        {
            EmitWithHandlersStmt(withHandlers, EmitUnitStatement);
            return;
        }
        // A discarded `match` likewise: as an expression it is a switch expression, and its
        // arms in this position are void — see EmitDiscardedMatchStmt.
        if (body is IrNode.Match match)
        {
            EmitDiscardedMatchStmt(match);
            return;
        }
        // And a discarded `let` — including the chain of discarded (`_`) bindings a `begin`
        // desugars to. Without this the spine goes through EmitLetExpr, which reintroduces an
        // immediately-invoked lambda immediately inside the `using`/`try` the two cases above
        // just flattened, since `(use ([m …]) (begin …))` binds its body as exactly that.
        //
        // Unlike a `using`/`try`, a local declared here lands directly in the *enclosing*
        // block, and PopLocal releases its identifier again — so two sibling spines binding
        // the same name would both emit it and collide (CS0128). A spine that declares
        // anything is therefore wrapped in a bare `{ }`; an all-`_` spine declares nothing
        // and needs no brace.
        if (body is IrNode.Let discardedLet)
        {
            var needsScope = LetSpineDeclaresLocal(discardedLet);
            if (needsScope)
            {
                EmitLine("{");
                _indent++;
            }
            EmitUnitLetSpine(discardedLet);
            if (needsScope)
            {
                _indent--;
                EmitLine("}");
            }
            return;
        }
        EmitLine(DiscardStatement(body, EmitExpr(body)));
    }

    /// Walks a discarded <c>let</c> spine, emitting each binding as a C# local statement and
    /// discarding the innermost body. A nested <c>let</c> is consumed here rather than
    /// re-entering <see cref="EmitUnitStatement"/> so the whole spine shares the single
    /// enclosing brace that caller opened, instead of nesting one brace per binding.
    ///
    /// <c>isAsync: false</c> holds for every path that reaches here: the async walker
    /// (<see cref="EmitAsyncStatementsBody"/>) matches <c>Let</c> itself, so it never falls
    /// through to the discard branch that delegates to <see cref="EmitUnitStatement"/>.
    private void EmitUnitLetSpine(IrNode.Let let)
    {
        var binding = EmitLetStmt(let, isAsync: false);
        if (let.Body is IrNode.Let nested)
            EmitUnitLetSpine(nested);
        else
            EmitUnitStatement(let.Body);
        if (binding is not null)
            PopLocal(binding.Value);
    }

    /// True when emitting <paramref name="node"/> as a discarded <c>let</c> spine would
    /// declare a C# local in the enclosing block — i.e. some binding on the spine is not the
    /// discarded <c>_</c>. Only the spine itself counts: an <c>if</c>, <c>use</c>, or
    /// <c>with-handlers</c> reached from it emits its own braces, so whatever those declare
    /// is already scoped. A <c>_</c> binding declares nothing either way — it emits
    /// <c>_ = …;</c> or runs a Unit-typed value for effect.
    private static bool LetSpineDeclaresLocal(IrNode node) =>
        node is IrNode.Let let && (let.VarName != "_" || LetSpineDeclaresLocal(let.Body));

    /// Renders <paramref name="body"/> as a statement to splice inline into a
    /// block lambda body (e.g. `() => { stmt return ...; }`). Returns the empty
    /// string for elidable Unit statements. See <see cref="IsElidableUnitStatement"/>.
    private static string InlineUnitStatement(IrNode body, string emitted) =>
        IsElidableUnitStatement(body) ? "" : $"{emitted}; ";

    /// Renders <paramref name="body"/> as a statement whose value is discarded —
    /// used both for Unit-returning function bodies and for the block body of a
    /// Unit-returning lambda (`(args) => {{ ... }}`). <paramref name="emitted"/> is
    /// the already-rendered C# for <paramref name="body"/>. Returns the empty
    /// string for an elidable Unit literal (the caller omits it).
    ///
    /// CS0201 permits only assignment, call, increment, decrement, await, and
    /// new-object expressions as statements. A node that emits one of those forms
    /// (<see cref="IsValidStatementExpr"/>) is emitted bare; every other
    /// value-producing expression — a literal, var ref, operator, ternary (`if`),
    /// switch (`match`), … — is discarded via `_ = expr;`. This holds even for
    /// Unit-typed expressions: `()` lowers to the *value* `default(System.ValueTuple)`
    /// and `(if c () ())` to a ternary over it, neither of which is a legal bare
    /// statement. Genuinely void-typed emissions (void CLR calls, `await`, `throw`,
    /// `set!`) are all themselves valid statement expressions, so they never reach
    /// the `_ =` branch where assigning void would itself be illegal.
    private static string DiscardStatement(IrNode body, string emitted)
    {
        if (IsElidableUnitStatement(body))
            return "";
        return IsValidStatementExpr(body) ? $"{emitted};" : $"_ = {emitted};";
    }

    /// Emits a body TailCallLowering turned into a loop (<c>IsTcoLoop</c>) as a
    /// <c>while (true)</c> whose every leaf terminates and whose every <see cref="IrNode.TcoJump" />
    /// reassigns the parameters and <c>continue</c>s. Shared by top-level functions
    /// (<see cref="EmitFuncDef" />) and sealed-class methods
    /// (<see cref="EmitInstanceMethodBody" />), whose parameters are assignable alike.
    private void EmitTailRecursiveLoop(IrNode body, ZType returnType, bool isAsync)
    {
        EmitLine("while (true)");
        EmitLine("{");
        _indent++;

        EmitStatementsBody(body, returnType, inLoop: true, isAsync: isAsync);

        _indent--;
        EmitLine("}");
    }

    /// Emits a <c>match</c> in TCO-loop statement position as a C# <c>switch</c> statement, so
    /// a tail self-call in an arm can lower to <c>continue</c> (a switch <em>expression</em>
    /// cannot host a statement). Every arm body is rendered via the shared statement-body
    /// walker in loop mode (<see cref="EmitStatementsBody" /> with <c>inLoop: true</c>) and
    /// therefore terminates (returns/continues/throws), so no case falls through. The
    /// scrutinee is bound to a local once; a Wildcard/Variable last arm becomes the
    /// unconditional <c>default:</c> (Variable additionally binds the scrutinee), everything
    /// else is a <c>case</c>. Each arm is emitted into its own <c>{ }</c> block, so pattern
    /// bindings are scoped per arm via <see cref="PushLocal" />/<see cref="PopLocals" /> — a
    /// binder renamed to dodge a collision must not leak into a sibling arm.
    private void EmitTcoLoopMatch(IrNode.Match match, ZType returnType, bool isAsync)
    {
        EmitMatchStmt(
            match,
            armBody => EmitStatementsBody(armBody, returnType, inLoop: true, isAsync),
            armsTerminate: true
        );
    }

    /// <summary>
    ///     Emits a <c>match</c> whose value is discarded as a C# <c>switch</c> statement.
    ///     A switch <em>expression</em> will not do: its arms here are void (an assertion, a
    ///     void CLR call), which is neither a legal statement expression (CS0201) nor
    ///     assignable through <c>_ =</c> (CS8209).
    /// </summary>
    private void EmitDiscardedMatchStmt(IrNode.Match match)
    {
        EmitMatchStmt(match, EmitUnitStatement, armsTerminate: false);
    }

    /// <param name="emitArmBody">Renders one arm's body into the arm's own block.</param>
    /// <param name="armsTerminate">
    ///     True when <paramref name="emitArmBody" /> always ends the arm with a
    ///     return/continue/throw, so no <c>break;</c> is needed; false when the arm falls off
    ///     the end of its block and C# requires one.
    /// </param>
    private void EmitMatchStmt(IrNode.Match match, Action<IrNode> emitArmBody, bool armsTerminate)
    {
        var scrutineeType = match.Scrutinee.Type;
        var scrutinee = EmitScrutinee(match.Scrutinee, match.Arms.Select(a => a.Pattern).ToList());
        var arms = PruneUnreachableArms(match.Arms, scrutineeType);

        var m = $"__match{_localBindCounter++}";
        EmitLine($"var {m} = {scrutinee};");
        EmitLine($"switch ({m})");
        EmitLine("{");
        _indent++;

        // A Wildcard/Variable last arm matches unconditionally and becomes `default:`. Every
        // other arm — including an irrefutable tuple/constructor — is a `case`; the compiler
        // does not treat those as always-matching, so a trailing `default: throw` stays legal.
        var lastIsUnconditional = arms[^1].Pattern is IrPattern.Wildcard or IrPattern.Variable;

        for (var i = 0; i < arms.Count; i++)
        {
            var arm = arms[i];
            // Scope this arm's pattern bindings to its own `{ }` block, pushing before the
            // block and popping after. Each arm is emitted into a separate braced block, so a
            // binder renamed by PushLocal (to dodge a collision with an enclosing local) is
            // lexically confined to that arm; keeping the rename live across arms would make a
            // later arm's reference to the original outer name resolve to the renamed, out-of-
            // scope identifier (CS0103). Mirrors the per-arm scoping in EmitMatch.
            var bindings = arm.Pattern.BoundNames().Select(PushLocal).ToList();

            if (i == arms.Count - 1 && lastIsUnconditional)
            {
                EmitLine("default:");
                EmitLine("{");
                _indent++;
                if (arm.Pattern is IrPattern.Variable)
                    EmitLine($"{EmitPattern(arm.Pattern, scrutineeType)} = {m};");
                emitArmBody(arm.Body);
                if (!armsTerminate)
                    EmitLine("break;");
                _indent--;
                EmitLine("}");
            }
            else if (
                arm.Pattern is IrPattern.Literal { Value: global::ZScheme.Runtime.ZSymbol sym }
            )
            {
                // A ZSymbol literal is not a C# constant, so guard on interned-reference
                // equality (matching EmitMatch and the IL backend).
                var g = $"__sym{_localBindCounter++}";
                EmitLine(
                    $"case var {g} when {g} == ZScheme.Runtime.ZSymbol.Intern(\"{EscapeString(sym.Name)}\"):"
                );
                EmitLine("{");
                _indent++;
                emitArmBody(arm.Body);
                if (!armsTerminate)
                    EmitLine("break;");
                _indent--;
                EmitLine("}");
            }
            else
            {
                EmitLine($"case {EmitPattern(arm.Pattern, scrutineeType)}:");
                EmitLine("{");
                _indent++;
                emitArmBody(arm.Body);
                if (!armsTerminate)
                    EmitLine("break;");
                _indent--;
                EmitLine("}");
            }

            PopLocals(bindings);
        }

        if (!lastIsUnconditional && !ArmsAreExhaustive(arms, scrutineeType))
        {
            EmitLine("default:");
            _indent++;
            EmitLine("throw new System.InvalidOperationException(\"Non-exhaustive match\");");
            _indent--;
        }

        _indent--;
        EmitLine("}");
    }

    private string EmitExpr(IrNode node)
    {
        return node switch
        {
            IrNode.IntConst n => FormatIntLiteral(n.Value),
            IrNode.FloatConst n => $"{n.Value.ToString(CultureInfo.InvariantCulture)}f",
            IrNode.BoolConst n => n.Value ? "true" : "false",
            IrNode.StringConst n => $"\"{EscapeString(n.Value)}\"",
            // Intern (not construct) so eq?/reference equality matches the IL backend. Reuse the
            // exact StringConst escaper so the interned name can't diverge between backends.
            IrNode.SymbolConst n => $"ZScheme.Runtime.ZSymbol.Intern(\"{EscapeString(n.Name)}\")",
            IrNode.UnitConst => "default(System.ValueTuple)",
            IrNode.NullConst => "null",
            IrNode.Var n => EmitVar(n),
            IrNode.Let n => EmitLetExpr(n),
            IrNode.Use n => EmitUseExpr(n),
            IrNode.If n => EmitIfExpr(n),
            IrNode.BinOp n => EmitBinOp(n),
            IrNode.UnaryOp n => EmitUnaryOp(n),
            IrNode.Call n => EmitCall(n),
            IrNode.ClrCall n => EmitClrCall(n),
            IrNode.FuncDef n => EmitLambdaExpr(n),
            IrNode.Closure n => EmitClosureExpr(n),
            IrNode.TupleNew n => $"({string.Join(", ", n.Elements.Select(EmitExpr))})",
            IrNode.RecordNew n => EmitRecordNew(n),
            IrNode.RecordWith n => EmitRecordWith(n),
            IrNode.FieldGet n =>
                $"{ParenthesizeReceiver(n.Record, EmitExpr(n.Record))}.{Sanitize(n.FieldName)}",
            IrNode.UnionCaseNew n => EmitUnionCaseNew(n),
            IrNode.Match n => EmitMatch(n),
            IrNode.MutableArrayNew n => EmitMutableArrayNew(n),
            IrNode.MethodCall n => EmitMethodCall(n),
            IrNode.ClrNew n => EmitClrNew(n),
            IrNode.TypeOf n => $"typeof({TypeToCs(n.TypeArg)})",
            IrNode.Throw n => EmitThrow(n),
            IrNode.WithHandlers n => EmitWithHandlers(n),
            IrNode.Await n => $"await {EmitExpr(n.Expr)}",
            IrNode.SuperMethodCall n => EmitSuperMethodCall(n),
            // No outer parens: `(this.X = expr);` is rejected as a statement
            // by C# (CS0201 — only assignment, call, increment, decrement,
            // await, and new-object expressions can be used as statements),
            // and `set!` is Unit-typed so it commonly lands in statement
            // position (e.g. inside `(begin (set! ...) ...)`). The bare
            // assignment is valid both as a statement and as an expression in
            // the contexts where SetField can appear (function args, ternary
            // arms, lambda bodies — all permit unparenthesized assignment).
            IrNode.SetField n => $"this.{Sanitize(n.FieldName)} = {EmitExpr(n.Value)}",
            _ => ErrorAndReturn(
                $"C# emission not implemented for {node.GetType().Name}",
                "default",
                node.Span
            ),
        };
    }

    private string EmitLetExpr(IrNode.Let n)
    {
        // The value belongs to the enclosing scope, so emit it before the binder is pushed.
        var valExpr = EmitExpr(n.Value);
        var varType = TypeToCs(LetVarType(n));

        // When the value is Unit-typed (e.g. a void CLR call like Console.WriteLine),
        // emit as a block lambda since void expressions can't be passed as arguments.
        // The binder is not declared at all in this shape (the value is a statement),
        // so no local is pushed.
        if (LetVarType(n) is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit })
        {
            var savedUnitSpace = BeginDeclarationSpace([]);
            var unitBodyExpr = EmitExpr(n.Body);
            EndDeclarationSpace(savedUnitSpace);
            var unitBodyType = TypeToCs(n.Body.Type);

            // In this shape the value is a statement *inside* the lambda, so an await in
            // either half has to be covered by the async form.
            var unitNeedsAsync = ContainsAwait(n.Value) || ContainsAwait(n.Body);

            // When body is also Unit (e.g. chained void calls in begin), both are statements
            var unitStmts = n.Body.Type is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit }
                ? $"{InlineUnitStatement(n.Value, valExpr)}{InlineUnitStatement(n.Body, unitBodyExpr)}return default(System.ValueTuple);"
                : $"{InlineUnitStatement(n.Value, valExpr)}return {unitBodyExpr};";

            return unitNeedsAsync
                ? $"(await ((System.Func<System.Threading.Tasks.Task<{unitBodyType}>>)(async () => {{ {unitStmts} }}))())"
                : $"((System.Func<{unitBodyType}>)(() => {{ {unitStmts} }}))()";
        }

        // The binding is carried by a lambda parameter, which opens a fresh declaration
        // space: it may legally shadow an enclosing local, so it never needs renaming —
        // but binders inside the body must not redeclare it.
        var savedSpace = BeginDeclarationSpace([]);
        var binding = PushLocal(n.VarName);
        var bodyExpr = EmitExpr(n.Body);
        var bodyType = TypeToCs(n.Body.Type);
        PopLocal(binding);
        EndDeclarationSpace(savedSpace);

        // Only the body lands inside the lambda here — the value is emitted in the enclosing
        // (already async, if it awaits) scope and passed as the argument.
        var needsAsync = ContainsAwait(n.Body);
        var param = $"({varType} {binding.EmittedName})";

        // When body is Unit-typed but the bound variable is not, emit as a block lambda
        // since void expressions can't be used directly as Func<> return values.
        if (n.Body.Type is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit })
        {
            var stmts = $"{InlineUnitStatement(n.Body, bodyExpr)}return default({bodyType});";
            return needsAsync
                ? $"(await ((System.Func<{varType}, System.Threading.Tasks.Task<{bodyType}>>)(async {param} => {{ {stmts} }}))({valExpr}))"
                : $"((System.Func<{varType}, {bodyType}>)({param} => {{ {stmts} }}))({valExpr})";
        }

        // Use an immediately invoked lambda for let-in-expression, wrapped in Func<> delegate cast
        return needsAsync
            ? $"(await ((System.Func<{varType}, System.Threading.Tasks.Task<{bodyType}>>)(async {param} => {bodyExpr}))({valExpr}))"
            : $"((System.Func<{varType}, {bodyType}>)({param} => {bodyExpr}))({valExpr})";
    }

    /// Emits a `use` in expression position as an immediately-invoked lambda whose
    /// body is a C# `using` block: `((Func<R>)(() => { using (var x = val) { return
    /// body; } }))()`. The native `using` lowers to try/finally that disposes the
    /// resource on every exit path. Mirrors <see cref="EmitWithHandlers"/>, including
    /// the async-lambda variant when the body awaits.
    private string EmitUseExpr(IrNode.Use n)
    {
        var resultType = TypeToCs(n.Type);
        var decl = n.VarType is not null ? TypeToCs(n.VarType) : "var";
        // Emit the resource value before registering the binding — it is not yet in scope.
        var valExpr = EmitExpr(n.Value);

        // The `using` sits inside an IIFE, so its variable lives in that lambda's fresh
        // declaration space and may legally shadow an enclosing local.
        var savedSpace = BeginDeclarationSpace([]);
        var binding = PushLocal(n.VarName);
        var bodyExpr = EmitExpr(n.Body);
        PopLocal(binding);
        EndDeclarationSpace(savedSpace);

        // A Unit-typed body can't be `return`ed (void expressions) — emit it as a
        // statement and return the unit value, matching EmitLetExpr's Unit handling.
        var bodyStmts = n.Body.Type is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit }
            ? $"{InlineUnitStatement(n.Body, bodyExpr)}return default(System.ValueTuple);"
            : $"return {bodyExpr};";

        var usingBlock = $"using ({decl} {binding.EmittedName} = {valExpr}) {{ {bodyStmts} }}";

        if (ContainsAwait(n.Body))
            return $"(await ((System.Func<System.Threading.Tasks.Task<{resultType}>>)(async () => {{ {usingBlock} }}))())";

        return $"((System.Func<{resultType}>)(() => {{ {usingBlock} }}))()";
    }

    /// Emits a `use` in statement position as a block-scoped C# `using` statement,
    /// recursing the body through <paramref name="emitBody"/> so a nested let/use/if
    /// spine flattens. The bound resource name is registered in <see cref="_localBindings"/>
    /// while the body is emitted so references resolve to it rather than a same-named
    /// module export.
    private void EmitUseStmt(IrNode.Use use, Action<IrNode> emitBody)
    {
        var decl = use.VarType is not null ? TypeToCs(use.VarType) : "var";
        // As in EmitLetStmt: the `using` variable is in scope over its own initializer,
        // so its identifier is reserved before the resource expression is emitted but
        // only becomes resolvable after.
        var reserved = ReserveLocalName(use.VarName);
        var valExpr = EmitExpr(use.Value);
        var binding = BindReservedLocal(reserved);
        EmitLine($"using ({decl} {binding.EmittedName} = {valExpr})");
        EmitLine("{");
        _indent++;
        emitBody(use.Body);
        _indent--;
        EmitLine("}");
        PopLocal(binding);
    }

    private string EmitIfExpr(IrNode.If n)
    {
        var cond = EmitExpr(n.Condition);
        // A Unit-typed `if` in expression position cannot be a C# ternary when a
        // branch is a genuinely void-typed expression (a void CLR call wrapped as
        // Unit, e.g. `vector-set!`): `void` is not a legal ternary operand
        // (CS0173) and the ternary itself is not a legal discarded statement
        // (CS0201). Emit a ValueTuple-returning block lambda that runs the
        // branches in statement form, yielding a real value usable anywhere an
        // expression is expected (a discarded `_ =`, an inline lambda body, a
        // nested ternary, …). Statement contexts emit `if` directly (see
        // EmitUnitStatement / EmitStatementsBody) and never reach this path. This
        // is what makes the `when`/`unless` macros — `(if test (begin …) ())` —
        // compile on the C# backend when the body is a single void call.
        if (n.Type is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit })
        {
            var thenStmt = InlineUnitStatement(n.Then, EmitExpr(n.Then));
            var elseStmt = InlineUnitStatement(n.Else, EmitExpr(n.Else));
            return $"((System.Func<System.ValueTuple>)(() => {{ if ({cond}) {{ {thenStmt}}} else {{ {elseStmt}}} return default(System.ValueTuple); }}))()";
        }
        var then = EmitExpr(n.Then);
        var @else = EmitExpr(n.Else);
        return $"({cond} ? {then} : {@else})";
    }

    private string EmitBinOp(IrNode.BinOp n)
    {
        var left = EmitExpr(n.Left);
        var right = EmitExpr(n.Right);
        var op = n.Op switch
        {
            "=" => "==",
            "!=" => "!=",
            "and" => "&&",
            "or" => "||",
            _ => n.Op,
        };
        // Integer `/` and `%` of two constant operands cannot be const-folded the
        // way the IL backend's `div`/`rem` opcodes evaluate them: Roslyn folds
        // `int.MinValue / -1` to `int.MinValue`, `int.MinValue % -1` to `0`, and
        // rejects `x / 0` outright as CS0020 — whereas the IL `div`/`rem` opcodes
        // throw OverflowException / DivideByZeroException at runtime. Force a
        // runtime evaluation by making the left operand opaque to the constant
        // folder (`Math.Max(x, x)` is an identity Roslyn won't fold through) so
        // both backends observe the same exception/value.
        if (n.Op is "/" or "%" && IsIntConstExpr(n.Left) && IsIntConstExpr(n.Right))
            return $"(System.Math.Max({left}, {left}) {op} {right})";
        // Other constant arithmetic (`+ - *`, plus float `/` and `%`) is folded by
        // Roslyn at compile time; overflow there becomes CS0220 in the default
        // checked context. ZScheme's semantics are unchecked (matches the IL
        // backend's `add/sub/mul` opcodes and IEEE float div/rem), so wrap
        // constant-only arithmetic in `unchecked(...)` to preserve wrap-around and
        // avoid the compile error without polluting general arithmetic with
        // redundant wrappers.
        if (
            n.Op is "+" or "-" or "*" or "/" or "%"
            && IsConstantExpr(n.Left)
            && IsConstantExpr(n.Right)
        )
            return $"unchecked({left} {op} {right})";
        return $"({left} {op} {right})";
    }

    private static bool IsConstantExpr(IrNode node)
    {
        return node switch
        {
            IrNode.IntConst
            or IrNode.FloatConst
            or IrNode.BoolConst
            or IrNode.StringConst
            or IrNode.SymbolConst
            or IrNode.UnitConst
            or IrNode.NullConst => true,
            IrNode.UnaryOp u => IsConstantExpr(u.Operand),
            IrNode.BinOp b => IsConstantExpr(b.Left) && IsConstantExpr(b.Right),
            // A C# ternary `c ? a : b` is a constant expression when all three
            // parts are constants — Roslyn will then fold it and apply CS0220 to
            // any overflowing arithmetic that reaches it.
            IrNode.If i => IsConstantExpr(i.Condition)
                && IsConstantExpr(i.Then)
                && IsConstantExpr(i.Else),
            _ => false,
        };
    }

    // True when the node is a compile-time-constant expression of integer type —
    // i.e. one whose Roslyn-folded `/` or `%` could diverge from the IL backend's
    // runtime `div`/`rem` opcodes. Mirrors IsConstantExpr but bottoms out only at
    // integer literals so float `/` and `%` (which fold identically to IEEE
    // semantics in both backends) keep the cheaper `unchecked(...)` path.
    private static bool IsIntConstExpr(IrNode node)
    {
        return node switch
        {
            IrNode.IntConst => true,
            IrNode.UnaryOp u when u.Op == "-" => IsIntConstExpr(u.Operand),
            IrNode.BinOp b when b.Op is "+" or "-" or "*" or "/" or "%" => IsIntConstExpr(b.Left)
                && IsIntConstExpr(b.Right),
            IrNode.If i => IsConstantExpr(i.Condition)
                && IsIntConstExpr(i.Then)
                && IsIntConstExpr(i.Else),
            _ => false,
        };
    }

    private string EmitUnaryOp(IrNode.UnaryOp n)
    {
        var operand = EmitExpr(n.Operand);
        var op = n.Op switch
        {
            "not" => "!",
            _ => n.Op,
        };
        // Negation of a constant int can fold at compile time and overflow
        // (`-int.MinValue`); wrap to match the unchecked semantics that the IL
        // backend's `neg` opcode produces.
        if (n.Op == "-" && IsConstantExpr(n.Operand))
            return $"unchecked(-({operand}))";
        return $"({op}({operand}))";
    }

    private string EmitCall(IrNode.Call n)
    {
        var args = string.Join(", ", n.Args.Select(EmitExpr));
        if (n.Function is IrNode.FuncDef lambda)
        {
            // An immediately-invoked lambda has no target type for C# to infer
            // against, so `(() => expr)(...)` fails with CS0149. Cast to a
            // Func<>/Action<> delegate so the invocation type-checks.
            var delegateType = LambdaDelegateType(lambda);
            return $"(({delegateType})({EmitLambdaExpr(lambda)}))({args})";
        }

        var func = EmitExpr(n.Function);

        // Direct calls to a known generic function need explicit type arguments
        // when emission contexts (immediately-invoked lambda casts, ternary arms,
        // etc.) hide the inference targets that Roslyn would otherwise use. The
        // simplest robust fix is to always instantiate generic calls explicitly.
        //
        // A local binding (parameter or let-bound name) shadows a module-scope
        // function of the same name — mirroring EmitVarRef — so an unqualified
        // call to such a binding invokes a delegate value, not the generic
        // function. Emitting `<...>` on a delegate invocation is invalid (CS0307),
        // so skip the generic-instantiation path for shadowed local bindings.
        if (
            n.Function is IrNode.Var v
            && !(v.ModuleName is null && _localBindings.Contains(v.Name))
            && TryLookupGenericFunc(v, out var info)
        )
        {
            var typeArgs = InferCallTypeArgs(info.FuncType, n);
            if (typeArgs is not null)
                return $"{func}<{typeArgs}>({args})";
        }

        return $"{func}({args})";
    }

    private string? InferCallTypeArgs(ZType.ZFuncType funcType, IrNode.Call call)
    {
        var freeVars = Substitution.FreeVars(funcType).OrderBy(id => id).ToList();
        if (freeVars.Count == 0)
            return null;
        var resolved = new ZType?[freeVars.Count];

        for (var i = 0; i < funcType.Params.Count && i < call.Args.Count; i++)
        {
            var actual = call.Args[i].Type;
            // Variadic: the formal final param is the element type T but the
            // actual arg has been packed into Clr-Array<T> by lowering.
            if (
                funcType.IsVariadic
                && i == funcType.Params.Count - 1
                && actual is ZType.ZNamedType { TypeArgs: [var elemType] } named
                && _typeAliases.IsArrayName(named.Name)
            )
                actual = elemType;
            MatchTypeVars(funcType.Params[i], actual, freeVars, resolved);
        }

        // Return type may carry vars not present in any parameter (e.g. zero-arg
        // generic constructors like `concurrent-dictionary/new`).
        MatchTypeVars(funcType.Return, call.Type, freeVars, resolved);

        var rendered = new List<string>(freeVars.Count);
        for (var i = 0; i < freeVars.Count; i++)
        {
            var t = resolved[i];
            if (t is null || IsFreeTypeVar(t))
                rendered.Add("int");
            else
                rendered.Add(TypeToCs(t));
        }

        return string.Join(", ", rendered);
    }

    private static void MatchTypeVars(
        ZType formal,
        ZType actual,
        List<int> freeVarIds,
        ZType?[] result
    )
    {
        switch (formal)
        {
            case ZType.ZTypeVar tv:
            {
                var idx = freeVarIds.IndexOf(tv.Id);
                if (idx >= 0 && result[idx] is null)
                    result[idx] = actual;
                return;
            }
            case ZType.ZConstrainedVar cv:
            {
                var idx = freeVarIds.IndexOf(cv.Id);
                if (idx >= 0 && result[idx] is null)
                    result[idx] = actual;
                return;
            }
            case ZType.ZNamedType fn when actual is ZType.ZNamedType an && fn.Name == an.Name:
            {
                for (var i = 0; i < fn.TypeArgs.Count && i < an.TypeArgs.Count; i++)
                    MatchTypeVars(fn.TypeArgs[i], an.TypeArgs[i], freeVarIds, result);
                return;
            }
            case ZType.ZFuncType ff when actual is ZType.ZFuncType af:
            {
                for (var i = 0; i < ff.Params.Count && i < af.Params.Count; i++)
                    MatchTypeVars(ff.Params[i], af.Params[i], freeVarIds, result);
                MatchTypeVars(ff.Return, af.Return, freeVarIds, result);
                return;
            }
            case ZType.ZNullableType fnn when actual is ZType.ZNullableType ann:
            {
                MatchTypeVars(fnn.Inner, ann.Inner, freeVarIds, result);
                return;
            }
        }
    }

    private string LambdaDelegateType(IrNode.FuncDef lambda)
    {
        if (lambda.ClrDelegateTypeName is not null)
            return lambda.ClrDelegateTypeName;
        var paramTypes = lambda.Params.Select(p => TypeToCs(p.Type)).ToList();
        if (lambda.ReturnType is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit })
            return paramTypes.Count == 0
                ? "System.Action"
                : $"System.Action<{string.Join(", ", paramTypes)}>";
        paramTypes.Add(TypeToCs(lambda.ReturnType));
        return $"System.Func<{string.Join(", ", paramTypes)}>";
    }

    /// <summary>
    ///     Parses a delegate type name (e.g. "System.Func&lt;int,int&gt;" or "System.Action")
    ///     and returns the parameter types that the delegate's Invoke method expects.
    /// </summary>
    private IReadOnlyList<string> ParseDelegateParameters(string delegateTypeName)
    {
        var genericOpen = delegateTypeName.IndexOf('<');
        if (genericOpen < 0)
            return []; // e.g. "System.Action" or custom non-generic delegate

        var genericClose = delegateTypeName.LastIndexOf('>');
        if (genericClose <= genericOpen)
            return [];

        var inner = delegateTypeName.Substring(genericOpen + 1, genericClose - genericOpen - 1);
        var args = SplitTypeArguments(inner);

        if (delegateTypeName.StartsWith("System.Func"))
        {
            // Last type argument is the return type — all preceding ones are parameters.
            if (args.Count <= 1)
                return [];
            return args.Take(args.Count - 1).ToList();
        }

        if (delegateTypeName.StartsWith("System.Action"))
        {
            // All type arguments are parameters.
            return args;
        }

        // Unknown delegate type — fall back to empty (existing behavior).
        return [];
    }

    private static List<string> SplitTypeArguments(string inner)
    {
        var args = new List<string>();
        var depth = 0;
        var start = 0;
        for (var i = 0; i < inner.Length; i++)
        {
            var c = inner[i];
            if (c == '<')
                depth++;
            else if (c == '>')
                depth--;
            else if (c == ',' && depth == 0)
            {
                args.Add(inner.Substring(start, i - start).Trim());
                start = i + 1;
            }
        }
        args.Add(inner.Substring(start).Trim());
        return args;
    }

    // Resolves a module name (e.g. "stdlib/error") to its emitted C# class name,
    // namespace-qualified when the module came from a precompiled package built under a
    // different namespace (e.g. ZScheme.StdLib.Stdlib_ErrorModule). Source-imported
    // modules share the current compilation's namespace, so they stay unqualified.
    private string QualifiedModuleClass(string moduleName)
    {
        var className = NameConverter.ClassNameFromModuleName(moduleName);
        return
            precompiledModuleNamespaces is not null
            && precompiledModuleNamespaces.TryGetValue(moduleName, out var ns)
            && ns.Length > 0
            ? $"{ns}.{className}"
            : className;
    }

    private string EmitVar(IrNode.Var n)
    {
        var baseRef = EmitVarRef(n);

        // Named-function reference passed to a delegate-typed CLR parameter: wrap it in
        // an adapter lambda cast to the target delegate type. This both selects the
        // correct overload (e.g. RequestDelegate over the minimal-API Delegate overload)
        // and coerces the function value, which is not implicitly convertible. The
        // adapter arity comes from the function's own signature (which matches the
        // delegate's Invoke arity, since that is why this overload was chosen).
        if (n.ClrDelegateTypeName is null)
            return baseRef;

        var arity = n.Type is ZType.ZFuncType ft
            ? ft.Params.Count
            : ParseDelegateParameters(n.ClrDelegateTypeName).Count;
        var argNames = Enumerable.Range(0, arity).Select(i => $"arg{i}").ToList();
        var paramList = string.Join(", ", argNames);
        var callArgs = string.Join(", ", argNames);
        return $"(({n.ClrDelegateTypeName})(({paramList}) => {baseRef}({callArgs})))";
    }

    private string EmitVarRef(IrNode.Var n)
    {
        // Overload-resolved reference: route directly to the named module's
        // class, bypassing the bare-name lookup (which is last-write-wins
        // when multiple imported modules export the same function name).
        if (n.ModuleName is not null)
            return $"{QualifiedModuleClass(n.ModuleName)}.{SanitizeFunc(n.EmitName, n.Name)}";

        // A local binder that had to be renamed to avoid shadowing an enclosing local:
        // resolve in-scope references to the fresh identifier. Only renamed bindings are
        // present, so non-shadowing names fall through unchanged. Placed before
        // field/local lookups so the binding shadows them within its scope, mirroring the
        // language's lexical scoping.
        if (_localRenames.TryGetValue(n.Name, out var renamed))
            return renamed;

        // Local bindings (parameters and let-bound names) shadow class fields and
        // module-scope functions alike. This check must precede both so a local
        // named `length` is not rewritten to an imported `length` function's
        // qualified static reference, and a method parameter or `let` that shares a
        // name with a field of the enclosing class resolves to the local rather than
        // `this.<Field>` — ZScheme's innermost-binding-wins scoping, matching the
        // type inferer and the IL backend.
        if (_localBindings.Contains(n.Name))
            return SanitizeParam(n.Name);

        if (_currentClassFields is not null && _currentClassFields.Contains(n.Name))
            return $"this.{Sanitize(n.Name)}";

        // Self/sibling (and inherited) instance-method calls within the class or
        // object currently being emitted. Without this, the bare method name falls
        // through to the camelCase parameter fallback and emits e.g. `countdown`
        // instead of `this.Countdown` (CS0103).
        if (_currentClassMethods is not null && _currentClassMethods.Contains(n.Name))
            return $"this.{Sanitize(n.Name)}";

        if (_funcToModuleClass.TryGetValue(n.Name, out var modClass))
            return $"{modClass}.{SanitizeFunc(n.EmitName, n.Name)}";

        // Inside a nested class the bare name would bind to that class's own member when
        // one shares the name — a field of a different type, say, which Roslyn then rejects
        // (CS0120 for an instance field reached from a static context). Qualifying with the
        // module class is unambiguous. Constructors need this as much as methods do: fields
        // are not even in scope there (TypeInferer.InferClassDecl binds only the ctor's
        // params), so a bare name that collides with a field is always the module function.
        if (_currentModuleNames.Contains(n.Name))
            return _inNestedClassBody
                ? $"{className}.{SanitizeFunc(n.EmitName, n.Name)}"
                : SanitizeFunc(n.EmitName, n.Name);

        return SanitizeParam(n.Name);
    }

    private string EmitClrCall(IrNode.ClrCall n)
    {
        Log.Debug(
            "CSharpEmitter: CLR call {TypeName}.{MethodName}, {ArgCount} args, hasOutParams={HasOut}, genericTypeArgs={HasGeneric}",
            n.QualifiedTypeName,
            n.MethodName,
            n.Args.Count,
            n.OutParams is { Count: > 0 },
            n.GenericTypeArgs is { Count: > 0 }
        );
        RecordClrTypeAssembly(n);
        if (n.OutParams is { Count: > 0 })
            return EmitOutParamStaticCall(
                $"{n.QualifiedTypeName}.{n.MethodName}",
                n.Args,
                n.OutParams,
                n.Type
            );

        // A static property/field (classified during lowering) is a member reference, not a
        // call — `LogLevel.Trace`, not `LogLevel.Trace()`.
        if (n.StaticMember is not ClrStaticMemberKind.None)
            return $"{n.QualifiedTypeName}.{n.MethodName}";

        var args = string.Join(", ", n.Args.Select(EmitExpr));
        if (n.GenericTypeArgs is { Count: > 0 })
        {
            var typeArgs = string.Join(", ", n.GenericTypeArgs.Select(TypeToCs));
            return $"{n.QualifiedTypeName}.{n.MethodName}<{typeArgs}>({args})";
        }

        return $"{n.QualifiedTypeName}.{n.MethodName}({args})";
    }

    /// <summary>
    ///     Notes which assembly the type name about to be spelled out resolved through, for
    ///     <see cref="ClrTypeAssemblies" />. Only records a member declared by the named type
    ///     itself: for an inherited member the resolved <c>DeclaringType</c> is a base type,
    ///     whose assembly says nothing about where the spelled name is found.
    /// </summary>
    private void RecordClrTypeAssembly(IrNode.ClrCall n)
    {
        if (n.ResolvedMethodInfo?.DeclaringType is not { } declaring)
            return;
        if (declaring.FullName != n.QualifiedTypeName)
            return;
        if (declaring.Assembly.GetName().Name is { } assemblyName)
            _clrTypeAssemblies[n.QualifiedTypeName] = assemblyName;
    }

    private string EmitClrNew(IrNode.ClrNew n)
    {
        var args = string.Join(", ", n.Args.Select(EmitExpr));
        var typeName = n.QualifiedTypeName;
        if (n.TypeArgs.Count > 0)
        {
            // Prefer the resolved type's type-args (post type-inference, with `^a`
            // annotations replaced by ZTypeVars that can be mapped to the enclosing
            // function's generic parameter names). The AST's literal n.TypeArgs still
            // carries `^a` strings, which would get sanitized to bogus identifiers.
            var typeArgsToEmit =
                n.Type is ZType.ZNamedType { TypeArgs.Count: > 0 } resolved
                && resolved.TypeArgs.Count == n.TypeArgs.Count
                    ? resolved.TypeArgs
                    : n.TypeArgs;
            typeName = $"{typeName}<{string.Join(", ", typeArgsToEmit.Select(TypeToCs))}>";
        }

        return $"new {typeName}({args})";
    }

    private string EmitOutParamMethodCall(
        string receiver,
        string methodName,
        IReadOnlyList<IrNode> visibleArgs,
        IReadOnlyList<ClrInterop.OutParamInfo> outParams,
        ZType returnType
    )
    {
        // Generate: ((System.Func<ReturnType>)(() => {
        //     var __out0 = default(T0); var __out1 = default(T1);
        //     var __ret = receiver.Method(arg0, out __out0, arg1, out __out1);
        //     return (__ret, __out0, __out1);
        // }))()
        var sb = new StringBuilder();
        sb.Append($"((System.Func<{TypeToCs(returnType)}>)(() => {{ ");

        var outParamCsTypes = ResolveOutParamCsTypes(outParams, returnType);
        // Declare out-param locals
        for (var i = 0; i < outParams.Count; i++)
            sb.Append($"{outParamCsTypes[i]} __out{i} = default; ");

        // Build the argument list interleaving visible args and out params
        var fullArgs = BuildOutParamArgList(visibleArgs, outParams);
        sb.Append($"var __ret = {receiver}.{methodName}({fullArgs}); ");
        sb.Append("return (__ret");
        for (var i = 0; i < outParams.Count; i++)
            sb.Append($", __out{i}");
        sb.Append("); }))()");
        return sb.ToString();
    }

    private string EmitOutParamStaticCall(
        string qualifiedCall,
        IReadOnlyList<IrNode> visibleArgs,
        IReadOnlyList<ClrInterop.OutParamInfo> outParams,
        ZType returnType
    )
    {
        var sb = new StringBuilder();
        sb.Append($"((System.Func<{TypeToCs(returnType)}>)(() => {{ ");

        var outParamCsTypes = ResolveOutParamCsTypes(outParams, returnType);
        for (var i = 0; i < outParams.Count; i++)
            sb.Append($"{outParamCsTypes[i]} __out{i} = default; ");

        var fullArgs = BuildOutParamArgList(visibleArgs, outParams);
        sb.Append($"var __ret = {qualifiedCall}({fullArgs}); ");
        sb.Append("return (__ret");
        for (var i = 0; i < outParams.Count; i++)
            sb.Append($", __out{i}");
        sb.Append("); }))()");
        return sb.ToString();
    }

    private string[] ResolveOutParamCsTypes(
        IReadOnlyList<ClrInterop.OutParamInfo> outParams,
        ZType returnType
    )
    {
        // OutParamInfo.ElementType comes from CLR reflection; for generic methods it
        // is the raw open generic parameter (e.g. ZNamedType("T")), which has no
        // mapping in the enclosing function's typeVarMap and would emit as a bogus
        // identifier. The call site's returnType is `(originalReturn, out0, out1, ...)`
        // built from the inferred types — preferring its tuple elements substitutes
        // those generic parameters with concrete or call-site type-vars correctly.
        var result = new string[outParams.Count];
        if (
            returnType is ZType.ZNamedType vt
            && _typeAliases.IsValueTupleName(vt.Name)
            && vt.TypeArgs.Count == outParams.Count + 1
        )
            for (var i = 0; i < outParams.Count; i++)
                result[i] = TypeToCs(vt.TypeArgs[i + 1]);
        else
            for (var i = 0; i < outParams.Count; i++)
                result[i] = TypeToCs(outParams[i].ElementType);
        return result;
    }

    private string EmitThrow(IrNode.Throw n)
    {
        return $"throw {EmitExpr(n.Expr)}";
    }

    private string EmitLambdaExpr(IrNode.FuncDef n)
    {
        Log.Debug(
            "CSharpEmitter: lambda expression, {ParamCount} params, returnType={ReturnType}",
            n.Params.Count,
            n.ReturnType
        );
        // A lambda body is a fresh declaration space: its params may legally shadow the
        // enclosing method's locals, but binders inside the body must not redeclare them.
        var savedSpace = BeginDeclarationSpace([]);
        var bindings = n.Params.Select(p => PushLocal(p.Name)).ToList();
        var body = EmitExpr(n.Body);
        PopLocals(bindings);
        EndDeclarationSpace(savedSpace);

        string parms;
        if (n.ClrDelegateTypeName is not null && n.Params.Count == 0)
        {
            // Lambda has no IR params but the delegate type expects parameters
            // (e.g. (lambda () : Int 42) cast to System.Func<int,int>).
            // Generate dummy parameters matching the delegate's signature so C# accepts it.
            var delegateParams = ParseDelegateParameters(n.ClrDelegateTypeName);
            parms =
                delegateParams.Count > 0
                    ? string.Join(", ", delegateParams.Select((t, i) => $"{t} arg{i}"))
                    : "";
        }
        else
        {
            parms = string.Join(
                ", ",
                n.Params.Select((p, i) => $"{TypeToCs(p.Type)} {bindings[i].EmittedName}")
            );
        }

        var lambdaExpr = n.ReturnType is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit }
            ? $"(({parms}) => {{ {DiscardStatement(n.Body, body)} }})"
            : $"(({parms}) => {body})";

        if (n.ClrDelegateTypeName is not null)
            return $"(({n.ClrDelegateTypeName}){lambdaExpr})";

        return lambdaExpr;
    }

    /// <summary>
    ///     Emits an <see cref="IrNode.Closure" /> produced by <see cref="ClosureConverter" />. The
    ///     capturing lambda has been lifted to a top-level static method with signature
    ///     <c>(captures..., original params...) -> return</c>; here we emit a native C# lambda that
    ///     closes over the captured values and forwards to it —
    ///     <c>((__c0, __c1) =&gt; Lifted(cap0, cap1, __c0, __c1))</c> — cast to the closure's
    ///     delegate type so it is self-typed in any expression position.
    /// </summary>
    private string EmitClosureExpr(IrNode.Closure n)
    {
        var funcName = SanitizeFunc(null, n.LiftedFuncName);
        var captureArgs = n.CapturedValues.Select(EmitExpr).ToList();

        string delegateType;
        int arity;
        switch (n.Type)
        {
            case ZType.ZFuncType ft:
            {
                var ps = ft.Params.Select(TypeToCs).ToList();
                arity = ps.Count;
                delegateType = ft.Return is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit }
                    ? ps.Count == 0
                        ? "System.Action"
                        : $"System.Action<{string.Join(", ", ps)}>"
                    : $"System.Func<{string.Join(", ", ps.Append(TypeToCs(ft.Return)))}>";
                break;
            }
            case ZType.ZDelegateType dt:
                delegateType = dt.ClrTypeName;
                arity = ParseDelegateParameters(dt.ClrTypeName).Count;
                break;
            default:
                return ErrorAndReturn(
                    $"C# emission: closure '{n.LiftedFuncName}' has non-function type "
                        + $"{n.Type?.GetType().Name}",
                    "default",
                    n.Span
                );
        }

        var paramNames = Enumerable.Range(0, arity).Select(i => $"__c{i}").ToList();
        var callArgs = string.Join(", ", captureArgs.Concat(paramNames));
        var paramList = string.Join(", ", paramNames);

        // A void (Action) delegate needs a statement body: the lifted method returns Unit
        // (default(ValueTuple)), which cannot be an Action's expression body.
        var isVoid = delegateType == "System.Action" || delegateType.StartsWith("System.Action<");
        var lambda = isVoid
            ? $"({paramList}) => {{ {funcName}({callArgs}); }}"
            : $"({paramList}) => {funcName}({callArgs})";
        return $"(({delegateType})({lambda}))";
    }

    private string EmitRecordNew(IrNode.RecordNew n)
    {
        var args = string.Join(
            ", ",
            n.Fields.Select(f => $"{Sanitize(f.FieldName)}: {EmitExpr(f.Value)}")
        );
        // For generic records/structs, emit the closed type args so C# does not require
        // ctor-inference (which our named-args form blocks anyway).
        var typeName = n.Type is ZType.ZNamedType { TypeArgs.Count: > 0 } nt
            ? TypeToCs(nt)
            : QualifyType(n.TypeName);
        return $"new {typeName}({args})";
    }

    private string EmitRecordWith(IrNode.RecordWith n)
    {
        // `(p) with { ... }` does not parse in C# because `(p)` looks like a cast operator.
        // Emit the record expression without wrapping parens and wrap the whole `with`
        // expression so the result composes safely inside larger expressions.
        var setters = string.Join(
            ", ",
            n.Updates.Select(u => $"{Sanitize(u.FieldName)} = {EmitExpr(u.Value)}")
        );
        return $"({EmitExpr(n.Record)} with {{ {setters} }})";
    }

    private string EmitUnionCaseNew(IrNode.UnionCaseNew n)
    {
        // Extract type args from the node's type (the union's named type with type arguments)
        var typeArgStr = "";
        if (n.Type is ZType.ZNamedType { TypeArgs.Count: > 0 } nt)
            typeArgStr = $"<{string.Join(", ", FormatTypeArgs(nt.Name, nt.TypeArgs))}>";

        var args = string.Join(", ", n.Args.Select(EmitExpr));
        return n.Args.Count == 0
            ? $"new {QualifyType(n.CaseName)}{typeArgStr}()"
            : $"new {QualifyType(n.CaseName)}{typeArgStr}({args})";
    }

    private string EmitMatch(IrNode.Match n)
    {
        Log.Debug(
            "CSharpEmitter: emitting match, {ArmCount} arms, scrutinee type={ScrutineeType}",
            n.Arms.Count,
            n.Scrutinee.Type
        );
        var scrutineeType = n.Scrutinee.Type;
        var scrutinee = EmitScrutinee(n.Scrutinee, n.Arms.Select(a => a.Pattern).ToList());

        // Drop unreachable trailing arms so Roslyn doesn't warn:
        //  - arms after any irrefutable pattern (wildcard/variable)
        //  - arms after bool exhaustiveness (both true and false literal patterns seen)
        var usefulArms = PruneUnreachableArms(n.Arms, scrutineeType);

        var sb = new StringBuilder();
        sb.Append($"{scrutinee} switch {{ ");

        foreach (var arm in usefulArms)
        {
            // Scope this arm's pattern bindings: a bound name that shadows an enclosing
            // local is renamed by PushLocal, since C# rejects a switch-expression pattern
            // variable colliding with an in-scope local (CS0136). EmitPattern's
            // declaration site and EmitVarRef's reference site both resolve through
            // `_localRenames`, and the binding is popped after the arm so it stays scoped
            // to it.
            var bindings = arm.Pattern.BoundNames().Select(PushLocal).ToList();

            var body = EmitExpr(arm.Body);
            if (arm.Pattern is IrPattern.Literal { Value: global::ZScheme.Runtime.ZSymbol sym })
            {
                // A ZSymbol literal is not a C# constant, so it can't be a switch pattern. Bind the
                // scrutinee and guard on value equality — evaluated once by the switch, and matching
                // the IL backend's interned-reference comparison.
                var g = $"__sym{_localBindCounter++}";
                sb.Append(
                    $"var {g} when {g} == ZScheme.Runtime.ZSymbol.Intern(\"{EscapeString(sym.Name)}\") => {body}, "
                );
            }
            else
            {
                var pattern = EmitPattern(arm.Pattern, scrutineeType);
                sb.Append($"{pattern} => {body}, ");
            }

            PopLocals(bindings);
        }

        // Only add fallback if the last arm isn't already a catch-all
        // and the arms aren't known to be exhaustive (e.g. bool with both true/false covered).
        var lastPattern = usefulArms[^1].Pattern;
        if (
            lastPattern is not IrPattern.Wildcard and not IrPattern.Variable
            && !IsIrrefutableForType(lastPattern, scrutineeType)
            && !ArmsAreExhaustive(usefulArms, scrutineeType)
        )
            sb.Append(
                "_ => throw new System.InvalidOperationException(\"Non-exhaustive match\"), "
            );
        sb.Append('}');
        return sb.ToString();
    }

    private List<IrMatchArm> PruneUnreachableArms(
        IReadOnlyList<IrMatchArm> arms,
        ZType? scrutineeType
    )
    {
        var isBool = scrutineeType is ZType.ZPrimitiveType { Kind: PrimitiveKind.Bool };
        var sawTrue = false;
        var sawFalse = false;
        // Float literal patterns are compared by IEEE 754 equality, so -0.0 and
        // 0.0 are the *same* pattern. Emitting both to a C# switch expression
        // trips CS8510 ("pattern is unreachable") — see fuzzer seed 0xf0ab7e8f.
        // Drop any float-literal arm whose value equals a prior one under `==`.
        var seenFloats = new List<float>();
        var result = new List<IrMatchArm>(arms.Count);
        foreach (var arm in arms)
        {
            if (arm.Pattern is IrPattern.Literal { Value: float f })
            {
                if (seenFloats.Any(s => s == f))
                    continue;
                seenFloats.Add(f);
            }

            result.Add(arm);
            if (IsIrrefutableForType(arm.Pattern, scrutineeType))
                break;
            if (isBool && arm.Pattern is IrPattern.Literal { Value: bool b })
            {
                if (b)
                    sawTrue = true;
                else
                    sawFalse = true;
                if (sawTrue && sawFalse)
                    break;
            }
        }

        return result;
    }

    private static bool ArmsAreExhaustive(IReadOnlyList<IrMatchArm> arms, ZType? scrutineeType)
    {
        if (scrutineeType is ZType.ZPrimitiveType { Kind: PrimitiveKind.Bool })
        {
            var sawTrue = false;
            var sawFalse = false;
            foreach (var arm in arms)
                if (arm.Pattern is IrPattern.Literal { Value: bool b })
                {
                    if (b)
                        sawTrue = true;
                    else
                        sawFalse = true;
                }

            return sawTrue && sawFalse;
        }

        return false;
    }

    private static bool IsIrrefutablePattern(IrPattern p)
    {
        return p switch
        {
            IrPattern.Wildcard => true,
            IrPattern.Variable => true,
            IrPattern.Tuple t => t.Elements.All(IsIrrefutablePattern),
            _ => false,
        };
    }

    /// <summary>
    ///     Type-aware irrefutability check. A pattern is irrefutable when it must
    ///     match every value of the scrutinee type, in which case Roslyn rejects a
    ///     trailing `_ =>` fallback as CS8510 ("pattern is unreachable"). Beyond the
    ///     always-irrefutable wildcard and variable patterns, this covers:
    ///     * tuple destructuring of `ValueTuple` whose elements are irrefutable
    ///     against the corresponding type argument;
    ///     * constructor patterns over single-case record/struct types whose
    ///     sub-patterns are themselves irrefutable.
    ///     A constructor pattern over a *union case* is never irrefutable — sibling
    ///     cases of the same union remain unmatched, so the fallback is required.
    /// </summary>
    private bool IsIrrefutableForType(IrPattern p, ZType? scrutineeType)
    {
        return p switch
        {
            IrPattern.Wildcard => true,
            IrPattern.Variable => true,
            IrPattern.Tuple t
                when scrutineeType is ZType.ZNamedType tup
                    && _typeAliases.IsValueTupleName(tup.Name)
                    && tup.TypeArgs.Count == t.Elements.Count => t
                .Elements.Zip(tup.TypeArgs)
                .All(pair => IsIrrefutableForType(pair.First, pair.Second)),
            // Without type info, a tuple of irrefutable sub-patterns is still
            // irrefutable (vars/wildcards bind anything).
            IrPattern.Tuple t => t.Elements.All(e => IsIrrefutableForType(e, null)),
            IrPattern.Constructor c
                when scrutineeType is ZType.ZNamedType named
                    && _recordTypeNames.Contains(named.Name)
                    && c.Name == named.Name => c.Fields.All(f => IsIrrefutableForType(f, null)),
            _ => false,
        };
    }

    /// <summary>
    ///     Emits a match scrutinee, widening any sub-expression whose emitted C# type is
    ///     narrower than its declared IR type back up to that type. A union-case
    ///     constructor call emits as `new Some&lt;int&gt;(...)`, which C# types at the case
    ///     subtype rather than the union base, so a pattern testing a sibling case
    ///     (`None&lt;int&gt;`) is provably impossible and Roslyn rejects it with CS8121.
    ///     The cast is only inserted where some arm actually tests a case in that
    ///     position, which keeps the emitted source clean everywhere else.
    ///     <para>
    ///         Tuples are walked element-wise so a union value inside a `values`
    ///         scrutinee is widened just like a direct one; each element is paired with
    ///         the patterns that land in its position.
    ///     </para>
    /// </summary>
    private string EmitScrutinee(IrNode scrutinee, IReadOnlyList<IrPattern> positionPatterns)
    {
        if (scrutinee is IrNode.TupleNew tuple)
        {
            var tuplePatterns = positionPatterns.OfType<IrPattern.Tuple>().ToList();
            var parts = tuple.Elements.Select(
                (element, i) =>
                    EmitScrutinee(
                        element,
                        tuplePatterns
                            .Where(p => i < p.Elements.Count)
                            .Select(p => p.Elements[i])
                            .ToList()
                    )
            );
            return $"({string.Join(", ", parts)})";
        }

        if (
            scrutinee.Type is ZType.ZNamedType named
            && ScrutineeNarrowsBelowIrType(scrutinee)
            && positionPatterns.Any(TestsAUnionCase)
        )
            return $"(({TypeToCs(named)}){EmitExpr(scrutinee)})";

        return EmitExpr(scrutinee);
    }

    /// <summary>
    ///     True if the pattern tests against a union case (or record type) rather than
    ///     just binding or matching a primitive value — i.e. the pattern position needs
    ///     its scrutinee widened to the declared type. See <see cref="EmitScrutinee" />.
    /// </summary>
    private static bool TestsAUnionCase(IrPattern p) => p is IrPattern.Constructor;

    /// <summary>
    ///     True if the scrutinee's emitted C# expression has a narrower C# type than
    ///     its IR `Type`. Today this happens only for <c>UnionCaseNew</c>: the IR type
    ///     is the union base, but the emitted `new CaseName&lt;...&gt;(...)` expression
    ///     types at the case subtype. Variable references, let bindings, calls, and
    ///     other expressions carry the declared IR type in C# already, so no cast is
    ///     needed for them.
    /// </summary>
    private static bool ScrutineeNarrowsBelowIrType(IrNode scrutinee)
    {
        return scrutinee switch
        {
            IrNode.UnionCaseNew => true,
            _ => false,
        };
    }

    private string EmitPattern(IrPattern p, ZType? scrutineeType)
    {
        return p switch
        {
            IrPattern.Wildcard => "_",
            IrPattern.Variable v =>
                $"var {(_localRenames.TryGetValue(v.Name, out var r) ? r : SanitizeParam(v.Name))}",
            IrPattern.Literal { Value: int i } => FormatIntLiteral(i),
            IrPattern.Literal { Value: float f } => $"{f.ToString(CultureInfo.InvariantCulture)}f",
            IrPattern.Literal { Value: bool b } => b ? "true" : "false",
            IrPattern.Literal { Value: string s } => $"\"{EscapeString(s)}\"",
            IrPattern.Tuple t => EmitTuplePattern(t, scrutineeType),
            IrPattern.Constructor c => EmitConstructorPattern(c, scrutineeType),
            _ => WarnAndReturn(
                $"Unsupported pattern type for C# emission: {p.GetType().Name}",
                "_"
            ),
        };
    }

    private string EmitTuplePattern(IrPattern.Tuple t, ZType? scrutineeType)
    {
        var elemTypes =
            scrutineeType is ZType.ZNamedType nt
            && _typeAliases.IsValueTupleName(nt.Name)
            && nt.TypeArgs.Count == t.Elements.Count
                ? nt.TypeArgs
                : null;
        var parts = t.Elements.Select(
            (e, i) => EmitPattern(e, elemTypes is null ? null : elemTypes[i])
        );
        return $"({string.Join(", ", parts)})";
    }

    private string EmitConstructorPattern(IrPattern.Constructor c, ZType? scrutineeType)
    {
        // The owning union and each field's scrutinee type were resolved by PatternResolver
        // (Ir/PatternResolver.cs) and attached to the pattern; the emitter no longer derives
        // union metadata itself.
        var qualifiedName = ResolveConstructorName(c.Name, scrutineeType, c.ResolvedUnion);

        if (c.Fields.Count == 0)
            return qualifiedName;

        var fields = string.Join(", ", c.Fields.Select((f, i) => EmitPattern(f, c.FieldTypes?[i])));
        return $"{qualifiedName}({fields})";
    }

    private string EmitMutableArrayNew(IrNode.MutableArrayNew n)
    {
        // For empty arrays, an unresolved type variable element (typically the
        // packed-args array of an empty variadic call like `(list)`) must
        // default to the same concrete type that InferCallTypeArgs picks at
        // the surrounding call site. Otherwise we emit
        // `Foo<int>(System.Array.Empty<object>())`, which Roslyn rejects with
        // a CS1503 conversion error.
        var elemType = n.ElementType;
        var csType = n.Elements.Count == 0 && IsFreeTypeVar(elemType) ? "int" : TypeToCs(elemType);
        if (n.Elements.Count == 0)
            return $"System.Array.Empty<{csType}>()";
        var elems = string.Join(", ", n.Elements.Select(EmitExpr));
        return $"new {csType}[] {{ {elems} }}";
    }

    private string EmitMethodCall(IrNode.MethodCall n)
    {
        Log.Debug(
            "CSharpEmitter: method call .{MethodName}, {ArgCount} args, isProperty={IsProperty}, isIndexer={IsIndexer}",
            n.MethodName,
            n.Args.Count,
            n.IsProperty,
            n.IsIndexer
        );
        var receiver = ParenthesizeReceiver(n.Receiver, EmitExpr(n.Receiver));
        var methodName = Sanitize(n.MethodName);
        if (n.IsPropertySet)
            return $"{receiver}.{n.MethodName} = {EmitExpr(n.Args[0])}";
        if (n.IsProperty)
            return $"{receiver}.{methodName}";
        if (n.IsIndexerSet)
            return $"{receiver}[{EmitExpr(n.Args[0])}] = {EmitExpr(n.Args[1])}";
        if (n.IsIndexer)
            return $"{receiver}[{EmitExpr(n.Args[0])}]";

        if (n.OutParams is { Count: > 0 })
            return EmitOutParamMethodCall(receiver, methodName, n.Args, n.OutParams, n.Type);

        var args = string.Join(", ", n.Args.Select(EmitExpr));
        return $"{receiver}.{methodName}({args})";
    }

    private string EmitWithHandlers(IrNode.WithHandlers n)
    {
        var resultType = TypeToCs(n.Type);
        var needsAsync = ContainsAwait(n.Body) || n.Handlers.Any(h => ContainsAwait(h.HandlerBody));
        var sb = new StringBuilder();

        // The try/catch sits inside an IIFE, whose body is a fresh declaration space:
        // catch variables and body locals may legally shadow the enclosing method's.
        var savedSpace = BeginDeclarationSpace([]);
        try
        {
            if (needsAsync)
            {
                // The body or a handler uses `await`. Emitting a sync `Func<T>` lambda
                // would put `await` inside a non-async lambda (CS4034). Emit an
                // `async () => Task<T>` lambda and await it so the awaits run inside
                // the enclosing async method.
                sb.Append(
                    $"(await ((System.Func<System.Threading.Tasks.Task<{resultType}>>)(async () => {{ try {{ return {EmitExpr(n.Body)}; }}"
                );
                foreach (var h in n.Handlers)
                    sb.Append(EmitCatchClause(h));

                sb.Append(" }))())");
                return sb.ToString();
            }

            sb.Append(
                $"((System.Func<{resultType}>)(() => {{ try {{ return {EmitExpr(n.Body)}; }}"
            );
            foreach (var h in n.Handlers)
                sb.Append(EmitCatchClause(h));

            sb.Append(" }))()");
            return sb.ToString();
        }
        finally
        {
            EndDeclarationSpace(savedSpace);
        }
    }

    /// Emits one `catch (Ex e) { return body; }` clause. The bound exception variable is
    /// pushed while the handler body is emitted, so a name shadowing an enclosing local
    /// is renamed rather than rejected by C# (CS0136).
    private string EmitCatchClause(IrHandlerClause h)
    {
        if (h.BindingVarName == "_")
            return $" catch ({h.ExceptionTypeName}) {{ return {EmitExpr(h.HandlerBody)}; }}";

        var binding = PushLocal(h.BindingVarName);
        var body = EmitExpr(h.HandlerBody);
        PopLocal(binding);
        return $" catch ({h.ExceptionTypeName} {binding.EmittedName}) {{ return {body}; }}";
    }

    /// Emits a <c>with-handlers</c> in statement position as a bare C# try/catch
    /// (each clause body recursed back through <paramref name="emitBody"/> so
    /// nested let/begin/if also flatten) instead of the immediately-invoked
    /// lambda <see cref="EmitWithHandlers"/> produces for expression position.
    /// The bound exception variable is registered in <see cref="_localBindings"/>
    /// while its handler body is emitted so nested references resolve to the
    /// catch variable rather than a same-named module export.
    private void EmitWithHandlersStmt(IrNode.WithHandlers n, Action<IrNode> emitBody)
    {
        EmitLine("try");
        EmitLine("{");
        _indent++;
        emitBody(n.Body);
        _indent--;
        EmitLine("}");
        foreach (var h in n.Handlers)
        {
            LocalBinding? binding = h.BindingVarName == "_" ? null : PushLocal(h.BindingVarName);
            EmitLine(
                binding is null
                    ? $"catch ({h.ExceptionTypeName})"
                    : $"catch ({h.ExceptionTypeName} {binding.Value.EmittedName})"
            );
            EmitLine("{");
            _indent++;
            emitBody(h.HandlerBody);
            _indent--;
            EmitLine("}");
            if (binding is not null)
                PopLocal(binding.Value);
        }
    }

    /// <summary>
    ///     True when an async function's declared return type emits as a bare
    ///     <c>System.Threading.Tasks.Task</c>, so its body must be a statement rather than a
    ///     <c>return</c> — <c>return expr;</c> in an <c>async Task</c> method is CS1997.
    ///     Covers both spellings a declaration can use: ZScheme <c>Unit</c>, and an explicit
    ///     result-less <c>Task</c> (what the <c>test-case-async</c> macro produces).
    /// </summary>
    private bool IsAsyncVoidReturn(ZType returnType)
    {
        return returnType == ZType.Unit
            || (
                returnType is ZType.ZNamedType { TypeArgs: [] } task
                && _typeAliases.IsTaskName(task.Name)
            );
    }

    private void EmitAsyncStatementsBody(IrNode body, bool isVoidReturn)
    {
        switch (body)
        {
            case IrNode.Let let:
            {
                // A binding whose value is itself a statement-form node (use /
                // with-handlers) must not be emitted as an expression here: an awaiting
                // body in expression position would wrap `await` in a non-async lambda
                // (CS4034) or emit a parenthesized await statement (CS0201). EmitLetStmt
                // owns those rules for every statement walker; `isAsync` selects them.
                var binding = EmitLetStmt(let, isAsync: true);
                EmitAsyncStatementsBody(let.Body, isVoidReturn);
                if (binding is not null)
                    PopLocal(binding.Value);
                break;
            }
            case IrNode.Use use:
                EmitUseStmt(use, b => EmitAsyncStatementsBody(b, isVoidReturn));
                break;
            case IrNode.If @if:
                EmitLine($"if ({EmitExpr(@if.Condition)})");
                EmitLine("{");
                _indent++;
                EmitAsyncStatementsBody(@if.Then, isVoidReturn);
                _indent--;
                EmitLine("}");
                EmitLine("else");
                EmitLine("{");
                _indent++;
                EmitAsyncStatementsBody(@if.Else, isVoidReturn);
                _indent--;
                EmitLine("}");
                break;
            case IrNode.WithHandlers wh:
                EmitWithHandlersStmt(wh, b => EmitAsyncStatementsBody(b, isVoidReturn));
                break;
            case IrNode.Throw:
                EmitLine($"{EmitExpr(body)};");
                break;
            default:
                if (isVoidReturn)
                    EmitUnitStatement(body);
                else
                    EmitLine($"return {EmitExpr(body)};");
                break;
        }
    }

    /// Emits a `let` as a C# local declaration and returns the binding it introduced,
    /// which the caller must keep open while emitting the let's body and then hand to
    /// <see cref="PopLocal"/>. Returns null for a discarded (`_`) binding, which
    /// declares no local. <paramref name="isAsync"/> tells the statement-form values below
    /// that they are being emitted into an async method, where a body may await.
    ///
    /// This is the single place a <c>let</c> becomes C# in statement position — every
    /// statement walker routes through it — so the rules for a value that is itself a
    /// statement-form node (<c>use</c>, <c>with-handlers</c>) live here rather than being
    /// repeated per walker.
    private LocalBinding? EmitLetStmt(IrNode.Let let, bool isAsync)
    {
        // A `use` or `with-handlers` in value position is itself a statement-form node:
        // routing it through EmitExpr below would bury the `using` / `try` in an
        // immediately-invoked lambda (EmitUseExpr / EmitWithHandlers). Emit the native C#
        // statement instead.
        if (let.Value is IrNode.Use useValue)
            return EmitUseInLetValue(let, useValue, isAsync);

        if (let.Value is IrNode.WithHandlers whValue)
            return EmitWithHandlersInLetValue(let, whValue, isAsync);

        // `_` is the desugared binding name for `begin` side-effect positions
        // (see AstBuilder.BuildBegin). Multiple nested `var _ = ...;` statements
        // would collide with CS0128 ("_ already defined"). Emit a discard
        // assignment instead, which is legal to repeat and carries the same
        // "evaluate and throw away" meaning.
        if (let.VarName == "_")
        {
            // For Unit-typed values (which lower to `void` in C#) we cannot
            // write `_ = voidCall()` — that's CS8209. Emit the call as a
            // statement instead. EmitLetExpr handles the same case for
            // expression position.
            if (LetVarType(let) is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit })
                EmitUnitStatement(let.Value);
            else
                EmitLine($"_ = {EmitExpr(let.Value)};");
            return null;
        }

        // The declared local is in scope over its own initializer, so reserve its
        // identifier before emitting the value — a binder inside the value (a match
        // arm's pattern variable, say) must not redeclare it. The value still *reads*
        // in the enclosing scope, so the name only becomes resolvable afterwards.
        var reserved = ReserveLocalName(let.VarName);
        var valExpr = EmitExpr(let.Value);
        var binding = BindReservedLocal(reserved);
        var decl = let.VarType is not null ? TypeToCs(let.VarType) : "var";
        EmitLine($"{decl} {binding.EmittedName} = {valExpr};");
        return binding;
    }

    /// Emits a <c>let</c> whose value is a <c>use</c> as a native C# <c>using</c> statement
    /// rather than the immediately-invoked lambda <see cref="EmitUseExpr"/> would produce.
    private LocalBinding? EmitUseInLetValue(IrNode.Let let, IrNode.Use use, bool isAsync) =>
        EmitStatementFormValueInLet(let, emitBody => EmitUseStmt(use, emitBody), isAsync);

    /// Emits a <c>let</c> whose value is a <c>with-handlers</c> as a bare C# try/catch rather
    /// than the immediately-invoked lambda <see cref="EmitWithHandlers"/> would produce.
    /// This is the shape stdlib's <c>catch</c> macro expands to, so it is by far the most
    /// common way the form is written: <c>(let ([r (catch (f))]) …)</c>.
    private LocalBinding? EmitWithHandlersInLetValue(
        IrNode.Let let,
        IrNode.WithHandlers wh,
        bool isAsync
    ) => EmitStatementFormValueInLet(let, emitBody => EmitWithHandlersStmt(wh, emitBody), isAsync);

    /// Emits a <c>let</c> whose value is itself a statement-form node — a <c>use</c> or a
    /// <c>with-handlers</c> — as the native C# statement instead of an immediately-invoked
    /// lambda. <paramref name="emitStmt"/> opens that statement (via <see cref="EmitUseStmt"/>
    /// or <see cref="EmitWithHandlersStmt"/>), taking the walker each of its bodies is
    /// recursed through.
    ///
    /// A `using`/`try` is a statement, so the let's local cannot be initialized by it
    /// directly: the local is *declared* first and every leaf of the embedded body *assigns*
    /// to it (<see cref="EmitAssignedStatementsBody"/>). C# definite-assignment accepts both
    /// shapes — a `using` block assigns on every path that completes normally, and a variable
    /// is definitely assigned after a try/catch when it is assigned at the end point of the
    /// try block *and* of every catch block. A leaf that throws has an unreachable end point,
    /// so it weakens neither case.
    ///
    /// A discarded (`_`) binding needs no local at all; its body is emitted for effect.
    /// Called only from <see cref="EmitLetStmt"/>, i.e. only in statement position.
    private LocalBinding? EmitStatementFormValueInLet(
        IrNode.Let let,
        Action<Action<IrNode>> emitStmt,
        bool isAsync
    )
    {
        if (let.VarName == "_")
        {
            // An awaiting body must stay in statement form: rendering it as an expression
            // would wrap `await` in a non-async lambda (CS4034). EmitAsyncStatementsBody
            // with isVoidReturn:true discards the value the same way EmitUnitStatement does.
            emitStmt(b =>
            {
                if (isAsync)
                    EmitAsyncStatementsBody(b, true);
                else
                    EmitUnitStatement(b);
            });
            return null;
        }

        // `var` is not available without an initializer, so the local needs its concrete
        // type — the same one EmitLetStmt would have inferred.
        var declType = TypeToCs(LetVarType(let));
        // As in EmitLetStmt: reserve the identifier before the value is emitted so binders
        // inside the statement (a `use` resource binder, a catch variable) cannot redeclare
        // it, but leave it unresolvable until afterwards — the resource expression and the
        // bodies read the *enclosing* scope's bindings.
        var reserved = ReserveLocalName(let.VarName);
        EmitLine($"{declType} {reserved.EmittedName};");
        emitStmt(b => EmitAssignedStatementsBody(b, reserved.EmittedName, isAsync));
        return BindReservedLocal(reserved);
    }

    /// Renders <paramref name="body"/> in statement position, assigning its value to the
    /// existing local <paramref name="target"/> at each leaf. The spine walk mirrors
    /// <see cref="EmitStatementsBody"/> (non-loop mode) and <see cref="EmitAsyncStatementsBody"/>
    /// — the two differ only in that the async walker expands *every* <c>if</c>, which
    /// <paramref name="isAsync"/> selects here — but the terminator is an assignment
    /// instead of a <c>return</c>. Used for a <c>use</c> lifted out of a <c>let</c> value
    /// (<see cref="EmitUseInLetValue"/>), where the value must land in a local declared
    /// outside the <c>using</c> block.
    ///
    /// An <c>await</c> at a leaf is fine (<c>target = await …;</c> is legal in an async
    /// method) because no lambda is introduced. <see cref="IrNode.TcoJump"/> cannot appear:
    /// a <c>use</c> is a tail barrier and a <c>let</c> value is never in tail position.
    private void EmitAssignedStatementsBody(IrNode body, string target, bool isAsync)
    {
        switch (body)
        {
            case IrNode.Let let:
            {
                var binding = EmitLetStmt(let, isAsync);
                EmitAssignedStatementsBody(let.Body, target, isAsync);
                if (binding is not null)
                    PopLocal(binding.Value);
                break;
            }
            case IrNode.Use nested:
                EmitUseStmt(nested, b => EmitAssignedStatementsBody(b, target, isAsync));
                break;
            case IrNode.WithHandlers wh:
                EmitWithHandlersStmt(wh, b => EmitAssignedStatementsBody(b, target, isAsync));
                break;
            case IrNode.If @if when isAsync || WantsStatementForm(@if):
                EmitLine($"if ({EmitExpr(@if.Condition)})");
                EmitLine("{");
                _indent++;
                EmitAssignedStatementsBody(@if.Then, target, isAsync);
                _indent--;
                EmitLine("}");
                EmitLine("else");
                EmitLine("{");
                _indent++;
                EmitAssignedStatementsBody(@if.Else, target, isAsync);
                _indent--;
                EmitLine("}");
                break;
            case IrNode.Throw:
                // Control never reaches the assignment, and `throw` is not an expression
                // this target could take anyway.
                EmitLine($"{EmitExpr(body)};");
                break;
            default:
                // A Unit-typed leaf may emit a genuinely void C# expression (a void CLR
                // call, `set!`, …), which cannot be assigned. Run it for effect and assign
                // the unit value instead — the same split EmitUseExpr makes for its
                // `return`.
                if (body.Type is ZType.ZPrimitiveType { Kind: PrimitiveKind.Unit })
                {
                    EmitUnitStatement(body);
                    EmitLine($"{target} = default(System.ValueTuple);");
                }
                else
                    EmitLine($"{target} = {EmitExpr(body)};");
                break;
        }
    }

    /// Renders <paramref name="body"/> in statement position, walking the
    /// <c>if</c>/<c>let</c>/<c>begin</c>/<c>match</c> tail spine and placing a terminator at
    /// each leaf. This is the single walker that owns the tail-position spine shape for both
    /// the ordinary statement-form function/method body (<paramref name="inLoop"/> false) and
    /// the body of a TCO <c>while (true)</c> loop (<paramref name="inLoop"/> true).
    ///
    /// The two modes differ only at the edges: a loop leaf must terminate the enclosing
    /// <c>while (true)</c> — a <see cref="IrNode.TcoJump"/> reassigns the parameters and
    /// <c>continue</c>s, and a <see cref="ZType.Unit"/> base case needs a trailing
    /// <c>return;</c> (without it control falls through and loops forever). The loop path also
    /// recurses into <em>every</em> <c>if</c> (a buried <see cref="IrNode.TcoJump"/> can never
    /// be an expression) and handles <c>begin</c>/<c>match</c> tails as statements, whereas the
    /// ordinary path expands an <c>if</c> only when a branch <see cref="WantsStatementForm"/>
    /// and lets a <c>match</c>/tail value fall through to the expression form. <c>TcoJump</c>,
    /// <c>Seq</c>, and <c>Match</c> only arise on the loop spine, so those cases are gated on
    /// <paramref name="inLoop"/>. No tail-position analysis happens here — the
    /// <see cref="IrNode.TcoJump"/> nodes were produced by <see cref="TailCallLowering"/>.
    ///
    /// <paramref name="isAsync"/> says the enclosing method is <c>async</c>, which is reachable
    /// only in loop mode: an awaiting non-loop body is claimed by
    /// <see cref="EmitAsyncStatementsBody"/> before this walker is reached. It selects the
    /// statement-form <c>let</c>-value rules (see <see cref="EmitLetStmt"/>) and keeps
    /// <c>use</c>/<c>with-handlers</c> leaves out of expression position, both of which would
    /// otherwise wrap an <c>await</c> in a non-async lambda (CS4034), and it recognises a bare
    /// <c>Task</c> return as void so a leaf does not emit <c>return expr;</c> (CS1997).
    private void EmitStatementsBody(IrNode body, ZType funcReturnType, bool inLoop, bool isAsync)
    {
        switch (body)
        {
            case IrNode.TcoJump jump when inLoop:
                // Evaluate the new arguments into temporaries first, so an argument that still
                // reads a parameter this jump overwrites (e.g. `(loop (g b) a)`) sees the old
                // value before the reassignment below.
                for (var i = 0; i < jump.NewArgs.Count; i++)
                    EmitLine($"var __tmp_{i} = {EmitExpr(jump.NewArgs[i])};");
                for (var i = 0; i < jump.NewArgs.Count; i++)
                    EmitLine($"{SanitizeParam(jump.ParamNames[i])} = __tmp_{i};");
                EmitLine("continue;");
                break;
            case IrNode.Let let:
            {
                var binding = EmitLetStmt(let, isAsync);
                EmitStatementsBody(let.Body, funcReturnType, inLoop, isAsync);
                if (binding is not null)
                    PopLocal(binding.Value);
                break;
            }
            // Use/WithHandlers are tail barriers (TailCallLowering never puts a TcoJump inside
            // one), so they only ever appear as a leaf on the loop spine; the ordinary path
            // reaches them here directly. In *synchronous* loop mode they fall through to the
            // base case below and emit as an expression, preserving the pre-merge loop output —
            // but an async loop must not do that: an awaiting body inside the immediately-invoked
            // lambda EmitUseExpr/EmitWithHandlers introduces is CS4034. A `return`/`continue`
            // emitted inside the resulting `using`/`try` is legal C# and still disposes.
            case IrNode.Use use when !inLoop || isAsync:
                EmitUseStmt(use, b => EmitStatementsBody(b, funcReturnType, inLoop, isAsync));
                break;
            case IrNode.If @if when inLoop || WantsStatementForm(@if):
                EmitLine($"if ({EmitExpr(@if.Condition)})");
                EmitLine("{");
                _indent++;
                EmitStatementsBody(@if.Then, funcReturnType, inLoop, isAsync);
                _indent--;
                EmitLine("}");
                EmitLine("else");
                EmitLine("{");
                _indent++;
                EmitStatementsBody(@if.Else, funcReturnType, inLoop, isAsync);
                _indent--;
                EmitLine("}");
                break;
            case IrNode.WithHandlers wh when !inLoop || isAsync:
                EmitWithHandlersStmt(
                    wh,
                    b => EmitStatementsBody(b, funcReturnType, inLoop, isAsync)
                );
                break;
            case IrNode.Seq seq when inLoop && seq.Nodes.Count > 0:
                // All but the last node run for effect; the last is in tail position.
                for (var i = 0; i < seq.Nodes.Count - 1; i++)
                    EmitUnitStatement(seq.Nodes[i]);
                EmitStatementsBody(seq.Nodes[^1], funcReturnType, inLoop, isAsync);
                break;
            case IrNode.Match match when inLoop:
                EmitTcoLoopMatch(match, funcReturnType, isAsync);
                break;
            case IrNode.Throw:
                EmitLine($"{EmitExpr(body)};");
                break;
            default:
                // Base case: produce the value and terminate. A void-returning function emits the
                // expression for effect; in a loop it then needs a bare `return;` to exit the
                // `while (true)` (a non-loop body simply falls off the method end).
                //
                // "Void" here is Unit, or — in an async method — a bare `Task`, whose declared
                // return type is not Unit but whose body still must not `return expr;` (CS1997).
                if (funcReturnType == ZType.Unit || (isAsync && IsAsyncVoidReturn(funcReturnType)))
                {
                    EmitUnitStatement(body);
                    if (inLoop)
                        EmitLine("return;");
                }
                else
                    EmitLine($"return {EmitExpr(body)};");
                break;
        }
    }

    /// Emits a class/object instance-method body, flattening let-spine and
    /// if-with-let-branch bodies into plain locals / if-else blocks (mirroring
    /// <see cref="EmitFuncDef"/>) instead of an immediately-invoked lambda.
    ///
    /// A method body is its own reference-resolution scope: it can see only its own
    /// parameters, its own locals, and the class's fields/methods. It can *not* see the
    /// locals of whatever function the emitter happened to be inside — an
    /// `(object ...)` expression is lifted out of its enclosing function, so at this
    /// point <see cref="_localBindings"/>/<see cref="_localRenames"/> still describe that
    /// function's scope. Left in place, a captured variable would resolve to the
    /// enclosing function's local (a bare name that does not exist here, or worse, the
    /// wrong same-named variable) instead of the capture field. Both are therefore
    /// cleared on entry and restored on exit, so bindings leak neither inward from the
    /// enclosing emit context nor outward into sibling methods.
    private void EmitInstanceMethodBody(
        IrNode body,
        ZType returnType,
        IReadOnlyList<IrParam> methodParams,
        bool isAsync,
        bool isTcoLoop
    )
    {
        var savedLocals = new HashSet<string>(_localBindings);
        var savedRenames = new Dictionary<string, string>(_localRenames);
        _localBindings.Clear();
        _localRenames.Clear();
        // Method parameters occupy C# identifiers that any binder inside the body must
        // not redeclare, so the body's declaration space is seeded with them.
        var savedSpace = BeginDeclarationSpace(methodParams);
        // Parameters are local bindings: they shadow a same-named field of the enclosing
        // class (and any same-named module function) during reference resolution.
        foreach (var p in methodParams)
            _localBindings.Add(p.Name);
        try
        {
            if (isTcoLoop)
                // Tail self-calls already lowered to TcoJump back-edges: same `while (true)`
                // as a top-level function's, and legal in an `async` method too — a C# `await`
                // inside a loop is exactly what the async body of one compiles to.
                EmitTailRecursiveLoop(body, returnType, isAsync);
            else if (isAsync && ContainsAwait(body))
                EmitAsyncStatementsBody(body, IsAsyncVoidReturn(returnType));
            else if (WantsStatementForm(body))
                // Only reached when the body contains no `await` at all (the branch above claims
                // it otherwise), so the synchronous walker can never bury one in a non-async
                // lambda — same reasoning as the EmitFuncDef call site.
                EmitStatementsBody(body, returnType, inLoop: false, isAsync: false);
            else if (returnType == ZType.Unit)
                // Through EmitUnitStatement, not a bare `{expr};`: not every expression is a
                // legal C# statement. A `match` emits a switch *expression*, which CS0201
                // rejects in statement position and which cannot be assigned through `_ =`
                // when its arms are void — the discard helpers already handle both.
                EmitUnitStatement(body);
            else
                EmitLine($"return {EmitExpr(body)};");
        }
        finally
        {
            EndDeclarationSpace(savedSpace);
            _localBindings.Clear();
            _localBindings.UnionWith(savedLocals);
            _localRenames.Clear();
            foreach (var (k, v) in savedRenames)
                _localRenames[k] = v;
        }
    }

    private void EmitTypeDeclarationsInline(IrNode node)
    {
        // When in a module context, type declarations are emitted inside the module class
        if (isModule)
            return;

        if (node is not IrNode.Seq seq)
            return;
        foreach (var child in seq.Nodes)
            switch (child)
            {
                case IrNode.RecordDecl rec:
                    Log.Debug("CSharpEmitter: emitting record {RecordName}", rec.Name);
                    EmitLine(EmitRecordDecl(rec));
                    EmitLine();
                    break;
                case IrNode.UnionDecl union:
                    Log.Debug(
                        "CSharpEmitter: emitting union {UnionName} with {CaseCount} cases",
                        union.Name,
                        union.Cases.Count
                    );
                    EmitLine(EmitUnionDecl(union));
                    EmitLine();
                    break;
                case IrNode.ClassDecl classDecl:
                    EmitClassDecl(classDecl);
                    EmitLine();
                    break;
                case IrNode.InterfaceDecl ifaceDecl:
                    EmitInterfaceDecl(ifaceDecl);
                    EmitLine();
                    break;
            }
    }

    private string EmitRecordDecl(IrNode.RecordDecl rec)
    {
        _recordTypeNames.Add(rec.Name);
        if (rec.TypeParamConstraints is { Count: > 0 })
            _typeParamConstraints[rec.Name] = (rec.TypeParams, rec.TypeParamConstraints);
        var sb = new StringBuilder();
        if (rec.Attributes is { Count: > 0 })
            foreach (var attr in rec.Attributes)
                sb.AppendLine(FormatAttribute(attr));
        var typeParams = rec.TypeParams.Count > 0 ? $"<{string.Join(", ", rec.TypeParams)}>" : "";
        var fields = string.Join(
            ", ",
            rec.Fields.Select(f =>
            {
                var fieldAttrs = FormatFieldAttributes(f.Attributes);
                return $"{fieldAttrs}{TypeToCs(f.Type)} {Sanitize(f.Name)}";
            })
        );
        var whereClause = FormatWhereConstraints(rec.TypeParamConstraints);
        var typeName = SanitizeType(rec.EmitName, rec.Name);
        var header = rec.IsValueType
            ? $"public readonly record struct {typeName}{typeParams}({fields}){whereClause};"
            : $"public sealed record {typeName}{typeParams}({fields}){whereClause};";
        sb.Append(header);
        return sb.ToString();
    }

    private string EmitUnionDecl(IrNode.UnionDecl union)
    {
        if (union.TypeParamConstraints is { Count: > 0 })
            _typeParamConstraints[union.Name] = (union.TypeParams, union.TypeParamConstraints);
        var typeParams =
            union.TypeParams.Count > 0 ? $"<{string.Join(", ", union.TypeParams)}>" : "";
        var sb = new StringBuilder();
        if (union.Attributes is { Count: > 0 })
            foreach (var attr in union.Attributes)
                sb.AppendLine(FormatAttribute(attr));
        var whereClause = FormatWhereConstraints(union.TypeParamConstraints);
        var unionName = SanitizeType(union.EmitName, union.Name);
        sb.AppendLine($"public abstract record {unionName}{typeParams}{whereClause};");
        foreach (var c in union.Cases)
        {
            var fields =
                c.Fields.Count > 0
                    ? $"({string.Join(", ", c.Fields.Select(f => $"{TypeToCs(f.Type)} {Sanitize(f.Name)}"))})"
                    : "()";
            sb.AppendLine(
                $"public sealed record {SanitizeType(c.EmitName, c.Name)}{typeParams}{fields} : {unionName}{typeParams}{whereClause};"
            );
        }

        return sb.ToString();
    }

    private void EmitClassDecl(IrNode.ClassDecl classDecl)
    {
        if (classDecl.TypeParamConstraints is { Count: > 0 })
            _typeParamConstraints[classDecl.Name] = (
                classDecl.TypeParams,
                classDecl.TypeParamConstraints
            );
        Log.Debug("CSharpEmitter: emitting class declaration {ClassName}", classDecl.Name);
        _currentTypeParams = classDecl.TypeParams.Count > 0 ? [.. classDecl.TypeParams] : null;
        // Emitted type name (collision-disambiguated); the constructor name must match it.
        var typeName = SanitizeType(classDecl.EmitName, classDecl.Name);

        if (classDecl.Attributes is { Count: > 0 })
            foreach (var attr in classDecl.Attributes)
                EmitLine(FormatAttribute(attr));

        var typeParams =
            classDecl.TypeParams.Count > 0 ? $"<{string.Join(", ", classDecl.TypeParams)}>" : "";

        // Build inheritance list: base class first (if any), then interfaces
        var baseList = new List<string>();
        if (classDecl.BaseClassName is not null)
            baseList.Add(QualifyType(classDecl.BaseClassName));
        baseList.AddRange(classDecl.InterfaceNames.Select(QualifyType));
        var inheritance = baseList.Count > 0 ? $" : {string.Join(", ", baseList)}" : "";

        var sealedModifier = classDecl.IsOpen ? "" : "sealed ";
        var whereClause = FormatWhereConstraints(classDecl.TypeParamConstraints);
        EmitLine($"public {sealedModifier}class {typeName}{typeParams}{inheritance}{whereClause}");
        EmitLine("{");
        _indent++;
        var savedInNestedClassBody = _inNestedClassBody;
        _inNestedClassBody = true;

        // Collect inherited fields and method names for override detection
        var inheritedFields = GetEmittedInheritedFields(classDecl.BaseClassName);
        var inheritedMethodNames = GetEmittedInheritedMethodNames(classDecl.BaseClassName);

        // Properties — only own fields, not inherited
        foreach (var field in classDecl.Fields)
        {
            var accessors =
                field.IsMutable ? "{ get; set; }"
                : field.IsInit ? "{ get; init; }"
                : "{ get; }";
            EmitLine($"public {TypeToCs(field.Type)} {Sanitize(field.Name)} {accessors}");
        }

        EmitLine();

        // Constructor
        if (classDecl.Constructor is { } ctor)
        {
            // Explicit constructor
            var ctorParams = string.Join(
                ", ",
                ctor.Params.Select(p => $"{TypeToCs(p.Type)} {SanitizeParam(p.Name)}")
            );
            // The `base(...)` arguments share the constructor's declaration space with its
            // parameters and body, so the space is opened *before* they are emitted: a
            // binder inside a base argument (a match arm's pattern variable, say) that
            // reuses a parameter's name is CS0136 otherwise.
            var savedCtorSpace = BeginDeclarationSpace(ctor.Params);
            // The parameters are local bindings too, not merely occupied identifiers: they
            // shadow any same-named module function during reference resolution, exactly as
            // EmitInstanceMethodBody arranges for a method's. Without this an object-lifted
            // class's capture parameter that collides with a module function (`f0` threaded
            // in beside `(define (f0 ...))`) resolved to the module name instead, and the
            // synthesized `this.F0 = <capture>` assigned the class's own property back to
            // itself. Whatever locals surround this emit are not in scope here — an object
            // class is emitted after its enclosing function — so they are cleared, and
            // restored on the way out.
            var savedCtorLocals = new HashSet<string>(_localBindings);
            var savedCtorRenames = new Dictionary<string, string>(_localRenames);
            _localBindings.Clear();
            _localRenames.Clear();
            foreach (var p in ctor.Params)
                _localBindings.Add(p.Name);
            var baseCall = ctor.SuperArgs is not null
                ? $" : base({string.Join(", ", ctor.SuperArgs.Select(EmitExpr))})"
                : "";
            EmitLine($"public {typeName}({ctorParams}){baseCall}");
            EmitLine("{");
            _indent++;
            foreach (var expr in ctor.BodyExprs)
                EmitLine($"{EmitExpr(expr)};");
            foreach (var (fieldName, value) in ctor.FieldSets)
                EmitLine($"this.{Sanitize(fieldName)} = {EmitExpr(value)};");
            EndDeclarationSpace(savedCtorSpace);
            _localBindings.Clear();
            _localBindings.UnionWith(savedCtorLocals);
            _localRenames.Clear();
            foreach (var (k, v) in savedCtorRenames)
                _localRenames[k] = v;
            _indent--;
            EmitLine("}");
        }
        else
        {
            // Auto-generated constructor
            var allParams = inheritedFields
                .Select(f => $"{TypeToCs(f.Type)} {Sanitize(f.Name)}")
                .ToList();
            allParams.AddRange(
                classDecl.Fields.Select(f => $"{TypeToCs(f.Type)} {Sanitize(f.Name)}")
            );
            var ctorParams = string.Join(", ", allParams);

            var baseCall =
                inheritedFields.Count > 0
                    ? $" : base({string.Join(", ", inheritedFields.Select(f => Sanitize(f.Name)))})"
                    : "";
            EmitLine($"public {typeName}({ctorParams}){baseCall}");
            EmitLine("{");
            _indent++;
            foreach (var field in classDecl.Fields)
                EmitLine($"this.{Sanitize(field.Name)} = {Sanitize(field.Name)};");
            _indent--;
            EmitLine("}");
        }

        // Methods
        _currentClassFields = new HashSet<string>(classDecl.Fields.Select(f => f.Name));
        // Include inherited fields so they resolve to this.FieldName. Skipped for
        // object-lifted classes: an `(object ...)` body does not bring the base
        // class's fields into bare-name scope (TypeInferer.InferObjectExpr), so a
        // bare name that collides with an inherited field is a module-level
        // function reference, not `this.<Field>` (which Roslyn rejects as CS1955
        // when the field is not invocable).
        if (!classDecl.IsObjectLifted)
            foreach (var f in inheritedFields)
                _currentClassFields.Add(f.Name);

        // Track method names (including inherited ones) so self/sibling calls
        // resolve to this.MethodName rather than the bare lowercase identifier.
        _currentClassMethods = new HashSet<string>(classDecl.Methods.Select(m => m.Name));
        foreach (var m in inheritedMethodNames)
            _currentClassMethods.Add(m);

        foreach (var method in classDecl.Methods)
        {
            EmitLine();
            if (method.Attributes is { Count: > 0 })
                foreach (var attr in method.Attributes)
                    EmitLine(FormatAttribute(attr));
            var retTypeStr = ReturnTypeToCs(method.ReturnType);
            var parms = string.Join(
                ", ",
                method.Params.Select(p => $"{TypeToCs(p.Type)} {SanitizeParam(p.Name)}")
            );

            // Determine virtual/override modifiers. A synthesized helper is private and plain:
            // both tests below key off the *name*, and a helper that happened to match an
            // inherited member would silently become an override of it. Its whole point is
            // that nothing can reach or replace it, which is also what lets TailCallLowering
            // loop it on an open class.
            var isOverride =
                !method.IsSynthesizedHelper && inheritedMethodNames.Contains(method.Name);
            var methodModifier =
                isOverride ? "override "
                : classDecl.IsOpen && !method.IsSynthesizedHelper ? "virtual "
                : "";
            var accessModifier = method.IsSynthesizedHelper ? "private" : "public";
            var asyncModifier = method.IsAsync ? "async " : "";

            EmitLine(
                $"{accessModifier} {asyncModifier}{methodModifier}{retTypeStr} {Sanitize(method.Name)}({parms})"
            );
            EmitLine("{");
            _indent++;
            EmitInstanceMethodBody(
                method.Body,
                method.ReturnType,
                method.Params,
                method.IsAsync,
                method.IsTcoLoop
            );
            _indent--;
            EmitLine("}");
        }

        _currentClassFields = null;
        _currentClassMethods = null;
        _inNestedClassBody = savedInNestedClassBody;

        _indent--;
        EmitLine("}");
        _currentTypeParams = null;

        // Store class info for future subclasses
        _emittedClassInfos[classDecl.Name] = new EmittedClassInfo(
            classDecl.IsOpen,
            classDecl.BaseClassName,
            classDecl.Fields,
            // Synthesized helpers are private, so a subclass can neither override one nor
            // reach it by bare name. Listing them here would feed both inheritedMethodNames
            // (turning a same-named derived method into an `override` of an inaccessible
            // member) and the derived class's bare-name scope, which would then emit
            // `this.__letrec_…` against a private base member.
            classDecl.Methods.Where(m => !m.IsSynthesizedHelper).Select(m => m.Name).ToList()
        );
    }

    private string EmitSuperMethodCall(IrNode.SuperMethodCall n)
    {
        var args = string.Join(", ", n.Args.Select(EmitExpr));
        return n.Args.Count > 0
            ? $"base.{Sanitize(n.MethodName)}({args})"
            : $"base.{Sanitize(n.MethodName)}()";
    }

    private void EmitInterfaceDecl(IrNode.InterfaceDecl ifaceDecl)
    {
        if (ifaceDecl.TypeParamConstraints is { Count: > 0 })
            _typeParamConstraints[ifaceDecl.Name] = (
                ifaceDecl.TypeParams,
                ifaceDecl.TypeParamConstraints
            );
        Log.Debug("CSharpEmitter: emitting interface {InterfaceName}", ifaceDecl.Name);
        _currentTypeParams =
            ifaceDecl.TypeParams.Count > 0 ? new HashSet<string>(ifaceDecl.TypeParams) : null;

        if (ifaceDecl.Attributes is { Count: > 0 })
            foreach (var attr in ifaceDecl.Attributes)
                EmitLine(FormatAttribute(attr));

        var typeParams =
            ifaceDecl.TypeParams.Count > 0 ? $"<{string.Join(", ", ifaceDecl.TypeParams)}>" : "";
        var baseInterfaces =
            ifaceDecl.BaseInterfaceNames.Count > 0
                ? $" : {string.Join(", ", ifaceDecl.BaseInterfaceNames.Select(QualifyType))}"
                : "";
        var whereClause = FormatWhereConstraints(ifaceDecl.TypeParamConstraints);
        EmitLine(
            $"public interface {SanitizeType(ifaceDecl.EmitName, ifaceDecl.Name)}{typeParams}{baseInterfaces}{whereClause}"
        );
        EmitLine("{");
        _indent++;

        foreach (var method in ifaceDecl.Methods)
        {
            var retTypeStr = ReturnTypeToCs(method.ReturnType);
            var parms = string.Join(
                ", ",
                method.Params.Select(p => $"{TypeToCs(p.Type)} {SanitizeParam(p.Name)}")
            );
            EmitLine($"{retTypeStr} {Sanitize(method.Name)}({parms});");
        }

        _indent--;
        EmitLine("}");
        _currentTypeParams = null;
    }

    private void EmitAttributes(IReadOnlyList<IrAttribute>? attrs)
    {
        if (attrs is null)
            return;
        foreach (var attr in attrs)
            EmitLine(FormatAttribute(attr));
    }

    private void EmitLine(string line = "")
    {
        if (string.IsNullOrEmpty(line))
        {
            _sb.AppendLine();
        }
        else
        {
            // Handle multiline strings by indenting each line
            var lines = line.Split('\n');
            foreach (var l in lines)
            {
                var trimmed = l.TrimEnd('\r');
                if (string.IsNullOrEmpty(trimmed))
                {
                    _sb.AppendLine();
                }
                else
                {
                    _sb.Append(new string(' ', _indent * 4));
                    _sb.AppendLine(trimmed);
                }
            }
        }
    }
